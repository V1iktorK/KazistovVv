// ================================================================================================
//  KvMrMenuFirstPlacementTests.cs — EditMode-тесты порядка «МЕНЮ → ВЫБОР МЕСТА → ПОДТВЕРЖДЕНИЕ».
//
//  ОТКУДА ЗАДАЧА (требование владельца 13.11.2026, дословно):
//    «Меня не устраивает, что при первом запуске MR сразу запускается робот, когда он должен
//     появиться после закрытия меню и должен появляться выбор установки робота на поверхность.
//     После подтверждения робот остаётся на этом месте.»
//
//  ЧТО БЫЛО НЕ ТАК. Отсчёт авто-постановки в `KvMrPlacement` начинался в `Start()`, то есть при
//  входе в MR, и про стартовое меню не знал вовсе. Через `autoPlaceDelaySeconds` (3 с) робот сам
//  вставал на «подтверждённый стол» и включался в мире: оператор ещё читал меню, а место за него уже
//  выбрала программа. Выбора места не происходило, а «подтверждение» подтверждало готовое.
//
//  КАК ПРОВЕРЯЕТСЯ БЕЗ ШЛЕМА И БЕЗ СЦЕНЫ. Сцена не запускается (правило проекта) и устройства нет,
//  поэтому проверяются ЧИСТЫЕ функции: `KvMrPlacement.ShouldAutoPlace`, `WaitForMenuToClose`,
//  `ShouldShowRobot`, строки журнала и флаг `AutoPlaceLocked`. Всё, от чего зависит видимое
//  поведение (появится ли робот, сколько ждать, что напечатается), закреплено здесь числом.
//
//  ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ: ЧТЕНИЯ ИСХОДНИКОВ С ДИСКА. Храповик P4-3 в
//  `Tools/acceptance-gate.ps1` считает файлы тестов, которые открывают тексты скриптов, и его порог
//  56 выбран по текущему составу набора: этот файл исходники не читает вовсе, поэтому счётчик НЕ
//  растёт. (Имена вызовов здесь намеренно не написаны: гейт ищет их простым совпадением по тексту
//  файла, и упоминание в комментарии посчиталось бы как настоящее чтение.) Поведение проверяется
//  через чистые функции — это строже грепа: ловится «правило решения», а не «текст на месте».
// ================================================================================================

using KazistovVvXr;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Робот в MR: скрыт до закрытия меню, затем выбор места, затем окончательная фиксация.</summary>
    [Category(KvTestCategories.Fast)]
    public class KvMrMenuFirstPlacementTests
    {
        /// <summary>Задержка авто-постановки по умолчанию — то же число, что в компоненте (3 с).</summary>
        private const float Delay = 3f;

        // ============================================================ а) МЕНЮ ОТКРЫТО — ЖДАТЬ

        /// <summary>
        /// ПРИ ОТКРЫТОМ МЕНЮ АВТО-ПОСТАНОВКА НЕ СРАБАТЫВАЕТ НИКОГДА (пункт 1–2 требования).
        ///
        /// ПОЧЕМУ ТРИ РАЗНЫХ ВРЕМЕНИ. Проверка «прошло 5 секунд — не ставим» не поймала бы ошибку
        /// «ставим, но позже»: правило могло бы просто увеличить задержку. Поэтому время берётся
        /// ВЕСЬМА разное — 5 с, 60 с и 300 с (5 минут, ровно как в требовании: «если меню открыто
        /// 5 минут — робот всё равно не появляется»), и во всех трёх случаях ответ обязан быть «нет».
        ///
        /// ЧТО БЫЛО: `elapsed = Time.unscaledTime - startedAt` (от старта MR) и никакой проверки меню —
        /// на всех трёх значениях робот был бы уже поставлен.
        /// </summary>
        [Test]
        public void AutoPlace_DoesNothingWhileMenuIsOpen_At5s60s300s()
        {
            float[] moments = { 5f, 60f, 300f };

            for (int i = 0; i < moments.Length; i++)
            {
                float seconds = moments[i];
                bool placed = KvMrPlacement.ShouldAutoPlace(
                    menuVisible: true, placeFixed: false, awaitingChoice: false,
                    hiddenUntilMenuClosed: true, secondsSinceMenuClosed: seconds, delaySeconds: Delay);

                Assert.IsFalse(placed,
                    "через " + seconds.ToString("0") + " с авто-постановка поставила робота ПРИ ОТКРЫТОМ " +
                    "МЕНЮ — это ровно жалоба владельца «при первом запуске MR сразу запускается робот»");
            }
        }

        /// <summary>
        /// ВРЕМЯ, ПРОВЕДЁННОЕ В МЕНЮ, НЕ ЗАСЧИТЫВАЕТСЯ (пункт 2 требования).
        ///
        /// ЧТО ПРОВЕРЯЕТСЯ. Правило `WaitForMenuToClose` говорит, когда опорное время таймера
        /// сдвигается на «сейчас». Пока меню открыто — сдвигается, значит отсчёт НАЧИНАЕТСЯ ЗАНОВО
        /// после выхода. Без этого «подождать закрытия» означало бы «дождаться, пока время в меню
        /// накопится», и робот появился бы мгновенно в момент закрытия.
        ///
        /// АНТИ-ВАКУУМ: после фиксации места время не сдвигается — иначе ожидание стало бы вечным.
        /// </summary>
        [Test]
        public void MenuTime_IsNotCounted_AutoPlaceStartsAfterClose()
        {
            Assert.IsTrue(KvMrPlacement.WaitForMenuToClose(true, false),
                "пока меню открыто, таймер авто-постановки обязан стоять: иначе 5 минут в меню " +
                "засчитаются как ожидание и робот появится сразу при закрытии");

            Assert.IsFalse(KvMrPlacement.WaitForMenuToClose(false, false),
                "меню закрыто — время обязано идти, иначе авто-постановка не сработает никогда");

            Assert.IsFalse(KvMrPlacement.WaitForMenuToClose(true, true),
                "место уже зафиксировано — сдвигать время незачем: авто-постановка выключена навсегда");
        }

        // ============================================================ б) ПОСЛЕ МЕНЮ — СРАБАТЫВАЕТ

        /// <summary>
        /// ПОСЛЕ ЗАКРЫТИЯ МЕНЮ АВТО-ПОСТАНОВКА РАБОТАЕТ — и только тогда (пункт 2 требования).
        ///
        /// ПРОВЕРЯЕТСЯ ГРАНИЦА, А НЕ «КОГДА-НИБУДЬ». До истечения задержки — «нет», на задержке и
        /// после — «да». Иначе проверка проходила бы и на правиле «никогда», и робот не появился бы
        /// вовсе (это второй способ сломать требование: не «слишком рано», а «никогда»).
        /// </summary>
        [Test]
        public void AutoPlace_WorksAfterMenuCloses_AndRespectsDelay()
        {
            // Меню закрыто, место не зафиксировано, оператор ещё не выбрал — время не пришло.
            Assert.IsFalse(KvMrPlacement.ShouldAutoPlace(false, false, false, false, Delay - 0.01f, Delay),
                "авто-постановка сработала РАНЬШЕ задержки — робот появится, пока оператор не смотрит");

            // Ровно на задержке — можно.
            Assert.IsTrue(KvMrPlacement.ShouldAutoPlace(false, false, false, false, Delay, Delay),
                "после закрытия меню и истечения задержки авто-постановка обязана работать: иначе " +
                "робот не появится НИКОГДА");

            // И заметно позже — тоже можно (таймер не «одноразовый»).
            Assert.IsTrue(KvMrPlacement.ShouldAutoPlace(false, false, false, false, 120f, Delay),
                "через две минуты после закрытия меню авто-постановка отказала — таймер сломан");
        }

        /// <summary>
        /// ПОКА РОБОТ СКРЫТ, АВТО-ПОСТАНОВКА МОЛЧИТ (пункт 1 требования).
        ///
        /// ОТДЕЛЬНАЯ ПРОВЕРКА, ПОТОМУ ЧТО ЭТО ДРУГОЙ ФЛАГ. `menuVisible` и `hiddenUntilMenuClosed` —
        /// разные вещи: меню может быть уже закрыто, а робот ещё не показан (кадр между закрытием и
        /// показом). Постановка в этот момент означала бы «поставили того, кого не видно».
        /// </summary>
        [Test]
        public void AutoPlace_IsOffWhileRobotIsHidden()
        {
            Assert.IsFalse(KvMrPlacement.ShouldAutoPlace(false, false, false, true, 60f, Delay),
                "робот ещё скрыт, а авто-постановка уже ставит его — оператор не увидит ни выбора, " +
                "ни результата");
        }

        // ============================================================ в) СКРЫТОСТЬ ДО МЕНЮ

        /// <summary>
        /// ДО ЗАКРЫТИЯ МЕНЮ РОБОТ ПОМЕЧЕН КАК СКРЫТЫЙ (пункт 1 требования, проверка по состоянию).
        ///
        /// ПОЧЕМУ ПРОВЕРЯЕТСЯ ПУБЛИЧНОЕ ПОЛЕ. Требование «при старте MR робота в мире НЕТ» нельзя
        /// доказать комментарием; поэтому у компонента есть ПУБЛИЧНЫЙ признак
        /// `RobotHiddenUntilMenuClosed`, и тест смотрит именно на него — так же, как приёмка смотрит
        /// на шлем. Живой компонент создаётся в памяти (сцена не правится).
        /// </summary>
        [Test]
        public void Placement_ExposesHiddenFlag_DefaultingToShownOutsideMenu()
        {
            var go = new GameObject("KvTestMrPlacementMenuFirst");
            try
            {
                KvMrPlacement placement = go.AddComponent<KvMrPlacement>();

                // СВЕЖИЙ КОМПОНЕНТ ВНЕ МЕНЮ РОБОТА НЕ ПРЯЧЕТ (анти-вакуум: иначе «скрыт всегда»).
                Assert.IsFalse(placement.RobotHiddenUntilMenuClosed,
                    "компонент вне меню сразу объявляет робота скрытым — робот не появится никогда");

                // Пока место не зафиксировано и выбор не начат, авто-постановка разрешена —
                // иначе правило «ждать меню» превратилось бы в «не ставить никогда».
                Assert.IsTrue(placement.CanAutoPlaceNow(menuVisible: false, secondsSinceMenuClosed: 60f),
                    "вне меню и без фиксации авто-постановка обязана быть разрешена");

                // При открытом меню — запрещена, сколько бы времени ни прошло.
                Assert.IsFalse(placement.CanAutoPlaceNow(menuVisible: true, secondsSinceMenuClosed: 300f),
                    "компонент разрешает авто-постановку при открытом меню — жалоба владельца вернётся");

                // ВЫХОД ИЗ МЕНЮ СНИМАЕТ СКРЫТОСТЬ: метод отвечает, что робота показали.
                Assert.IsTrue(placement.BeginOperatorChoice(),
                    "выход из меню не снял скрытость — робот останется невидимым при выборе места");
                Assert.IsFalse(placement.RobotHiddenUntilMenuClosed,
                    "после начала выбора места робот обязан быть помечен видимым");
                Assert.IsTrue(placement.AwaitingOperatorChoice,
                    "выбор места не отмечен — авто-постановка снова начнёт решать за оператора");
            }
            finally
            {
                Object.DestroyImmediate(go);
            }
        }

        /// <summary>
        /// ПРАВИЛО ПОКАЗА РОБОТА — ЧИСТАЯ ФУНКЦИЯ: меню видно → робота не видно.
        ///
        /// АНТИ-ВАКУУМ: меню НЕ открывалось (запуск сразу в мире, планшет с подавленным меню) →
        /// робот виден. Без этой половины правило легко превратить в «робот не показывается никогда»,
        /// и приложение станет пустым — второй, более тихий способ сломать требование.
        /// </summary>
        [Test]
        public void ShouldShowRobot_IsFalseOnlyWhileMenuIsVisible()
        {
            Assert.IsFalse(KvMrPlacement.ShouldShowRobot(true),
                "меню открыто, а робот показывается — «при первом запуске MR сразу запускается робот»");
            Assert.IsTrue(KvMrPlacement.ShouldShowRobot(false),
                "меню закрыто (или его не было), а робот скрыт — оператор не увидит выбора места");
        }

        // ============================================================ г) ФИКСАЦИЯ БЛОКИРУЕТ

        /// <summary>
        /// ПОСЛЕ ПОДТВЕРЖДЕНИЯ МЕСТА АВТО-ПОСТАНОВКА РОБОТА НЕ ДВИГАЕТ (пункты 4–5 требования).
        ///
        /// ЧТО БЫЛО. Фиксация запоминала точку, но таймер продолжал работать: раз в 4 секунды робот
        /// уезжал «на подтверждённый стол». Владелец видел, что место не держится.
        /// ЧТО ПРОВЕРЯЕТСЯ. Живой компонент: после `LockPlacement` чистое правило отвечает «нет» при
        /// ЛЮБОМ времени и при любом состоянии меню — блокирует именно флаг «зафиксировано».
        /// </summary>
        [Test]
        public void AfterFix_AutoPlaceNeverMovesRobotAgain()
        {
            var go = new GameObject("KvTestMrPlacementLocked");
            try
            {
                KvMrPlacement placement = go.AddComponent<KvMrPlacement>();
                placement.LockPlacement("подтверждено клавишей B");

                Assert.IsTrue(placement.AutoPlaceLocked,
                    "фиксация не выключила авто-постановку — робот уедет с утверждённого места");

                float[] moments = { 0f, 3f, 60f, 300f, 3600f };
                for (int i = 0; i < moments.Length; i++)
                {
                    Assert.IsFalse(placement.CanAutoPlaceNow(false, moments[i]),
                        "через " + moments[i].ToString("0") + " с после фиксации авто-постановка снова " +
                        "двигает робота — «после подтверждения робот остаётся на этом месте» нарушено");
                }

                // И при открытом меню — тоже нет (проверка не должна зависеть от одного условия).
                Assert.IsFalse(placement.CanAutoPlaceNow(true, 300f),
                    "при открытом меню после фиксации авто-постановка снова разрешена");

                // Само правило, без компонента: фиксация перебивает даже «всё остальное готово».
                Assert.IsFalse(KvMrPlacement.ShouldAutoPlace(false, true, false, false, 600f, 0f),
                    "правило разрешает постановку при placeFixed = true — фиксация ничего не значит");
            }
            finally
            {
                Object.DestroyImmediate(go);
            }
        }

        /// <summary>
        /// СТРОКА ФИКСАЦИИ ГОВОРИТ ИСТОЧНИК (КАКОЙ ЛУЧ) И ЧТО АВТО-ПОСТАНОВКА ОТКЛЮЧЕНА.
        ///
        /// ФОРМА:
        ///   `[KvMr] МЕСТО РОБОТА ЗАФИКСИРОВАНО: (0.42; 0.78; 1.05) м · луч правый · поворот 30° ·
        ///    подтверждено B · авто-постановка отключена`
        ///
        /// ПОЧЕМУ ИСТОЧНИК ОБЯЗАТЕЛЕН (решение владельца 13.11.2026): в MR два луча, и они делают
        /// РАЗНОЕ — правый (зелёный) выбирает место и траекторию робота, левый (красный) выбирает точку
        /// на плоскости, как в ПК-версии. Строка без источника не даёт понять по журналу, чем
        /// подтверждали, — а это ровно тот вопрос, который задают при разборе «робот встал не туда».
        ///
        /// ПОЧЕМУ ЦЕЛИКОМ, А НЕ «СОДЕРЖИТ ЧИСЛО». Строка — единственное доказательство в журнале
        /// шлема, что место закреплено. Приёмка ищет её по точному виду, поэтому проверяется точное
        /// равенство, а не набор слов.
        /// </summary>
        [Test]
        public void FixedLine_MatchesOwnerWording_AndSaysAutoPlaceOff()
        {
            string line = KvMrRobotPick.DescribeFixed(new Vector3(0.42f, 0.78f, 1.05f), 30f, "B");

            Assert.AreEqual(
                "[KvMr] МЕСТО РОБОТА ЗАФИКСИРОВАНО: (0.42; 0.78; 1.05) м · луч правый · поворот 30° · " +
                "подтверждено B · авто-постановка отключена",
                line,
                "строка фиксации разошлась с требованием владельца — приёмка её не найдёт");

            StringAssert.Contains("авто-постановка отключена", line,
                "в строке фиксации нет главного факта: после подтверждения авто-постановка выключена");

            // ИСТОЧНИК НАЗВАН ЯВНО: иначе при двух лучах непонятно, чем подтверждали.
            StringAssert.Contains(KvMrRobotPick.RaySourceName(), line,
                "строка фиксации не называет, каким лучом зафиксировано место");
            Assert.AreEqual("луч правый", KvMrRobotPick.RaySourceName(),
                "место робота фиксируется ПРАВЫМ (зелёным) лучом: левый выбирает точку на плоскости");
        }

        // ============================================================ д) АНТИ-ВАКУУМ

        /// <summary>
        /// АНТИ-ВАКУУМ: ЕСЛИ МЕНЮ НЕ ОТКРЫВАЛОСЬ ВОВСЕ, ПРАВИЛО НЕ БЛОКИРУЕТ РАБОТУ НАВСЕГДА.
        ///
        /// ЧЕМ ЭТО ГРОЗИЛО. Требование «ждать закрытия меню» легко превратить в «ждать всегда»:
        /// достаточно сравнивать не с фактом видимости меню, а с флагом «меню когда-то было».
        /// Тогда запуск сразу в мире (AR на планшете: `KvXrStartMenu.SuppressAutoShow`; повторный
        /// вход в MR, когда меню уже закрыто) оставлял бы оператора БЕЗ РОБОТА и без объяснения.
        ///
        /// КАК ПРОЕКТ ЭТО РЕШАЕТ — ТРИ КОНКРЕТНЫХ МЕСТА, и все три закреплены ниже:
        ///   1) ожидание включается ТОЛЬКО по факту «меню видно СЕЙЧАС» (`WaitForMenuToClose`), а не
        ///      по «меню открывали когда-либо» — нет меню, нет ожидания;
        ///   2) показ робота решается по видимости меню СЕЙЧАС (`ShouldShowRobot(false) == true`),
        ///      поэтому робот, скрытый до меню, показывается и без всякой церемонии закрытия;
        ///   3) `BeginOperatorChoice` снимает скрытость и явно зовётся из выхода из меню, из режима
        ///      выбора и из успешной постановки — то есть «выключателей скрытости» три, и любой из них
        ///      достаточно.
        /// </summary>
        [Test]
        public void AutoPlace_WithoutMenu_IsNotBlockedForever()
        {
            // 1) Меню не открывалось: время идёт с самого начала, ожидания нет.
            Assert.IsFalse(KvMrPlacement.WaitForMenuToClose(false, false),
                "ожидание включилось без меню — робот не появится никогда");

            // 2) И авто-постановка разрешена, как только истекла задержка.
            Assert.IsTrue(KvMrPlacement.ShouldAutoPlace(
                    menuVisible: false, placeFixed: false, awaitingChoice: false,
                    hiddenUntilMenuClosed: false, secondsSinceMenuClosed: 30f, delaySeconds: Delay),
                "без меню авто-постановка заблокирована навсегда — запуск сразу в мире останется без робота");

            // 3) Робот показывается без всякого закрытия меню (меню просто не было).
            Assert.IsTrue(KvMrPlacement.ShouldShowRobot(false),
                "робот скрыт при отсутствии меню — «не появится никогда»");

            // 4) Второй выключатель скрытости: выход из меню снимает флаг даже без фиксации.
            var go = new GameObject("KvTestMrPlacementAntiVacuum");
            try
            {
                KvMrPlacement placement = go.AddComponent<KvMrPlacement>();
                placement.BeginOperatorChoice();
                Assert.IsFalse(placement.RobotHiddenUntilMenuClosed,
                    "скрытость не снимается командой «начать выбор места» — робота не вернуть в мир");
            }
            finally
            {
                Object.DestroyImmediate(go);
            }
        }
    }
