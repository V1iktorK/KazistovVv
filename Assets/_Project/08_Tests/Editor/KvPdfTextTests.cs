// ================================================================================================
//  KvPdfTextTests.cs — EditMode-тесты ТЕКСТА В PDF-ОТЧЁТЕ (сессия S44).
//
//  ОТКУДА ЗАДАЧА. Отчёт PDF собирается встроенными средствами (без внешних библиотек) со шрифтом
//  `WinAnsiEncoding` — это кодировка Windows-1252, где есть только латиница. Поэтому перед записью
//  текст проходит через `Latin()` (транслитерация кириллицы) и затем через `Escape()`, который
//  заменяет ЛЮБОЙ символ вне печатного ASCII на `?`.
//
//  ЧТО ЭТО ЗНАЧИТ ДЛЯ НЕАНГЛИЙСКИХ ЯЗЫКОВ (найдено 30.10.2026, проверено чтением кода):
//    • русский текст — транслитерируется в латиницу, читается нормально;
//    • КИТАЙСКИЙ и ЯПОНСКИЙ — НЕ переводятся и НЕ имеют латинского эквивалента, поэтому каждый
//      иероглиф превращается в `?`. Отчёт на китайском языке выйдет строкой вопросительных знаков;
//    • эмодзи и редкие символы — так же.
//
//  ПОЧЕМУ ЭТО НЕ ИСПРАВЛЕНО ЗДЕСЬ. Правильное решение — встроить TTF-шрифт с CJK-глифами и
//  использовать кодировку Identity-H (двухбайтовую). Это замена ядра генератора PDF: нужен файл
//  шрифта (решение владельца, как с 5.27) и отдельная работа. Сегодня ночью правильнее ЧЕСТНО
//  ЗАКРЕПИТЬ известное ограничение тестом, чем ломать работающий генератор перед субботой.
//
//  ЧТО ЗАКРЕПЛЯЕТСЯ:
//    1) латиница проходит БЕЗ изменений (иначе отчёт испортится на английском);
//    2) кириллица транслитерируется и остаётся ЧИТАЕМОЙ;
//    3) опасные для PDF символы `(`, `)`, `\` ЭКРАНИРУЮТСЯ (иначе файл не откроется);
//    4) ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ: иероглифы становятся `?` — тест документирует это и покраснеет,
//       когда ограничение уберут, напомнив обновить отчёт.
// ================================================================================================

using KazistovVvFeatures;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Текст PDF-отчёта: транслитерация, экранирование и известное ограничение CJK.</summary>
    public class KvPdfTextTests
    {
        // ------------------------------------------------------------------ 1. ЛАТИНИЦА

        /// <summary>
        /// ЛАТИНИЦА ПРОХОДИТ БЕЗ ИЗМЕНЕНИЙ. Если транслитерация тронет английский текст, отчёт на
        /// английском станет нечитаемым — а это основной язык экспорта.
        /// </summary>
        [Test]
        public void LatinTextIsUnchanged()
        {
            const string source = "Trajectory report: time 12.5 s, length 3.42 m";
            string result = KvPdfWriter.Latin(source);

            Assert.AreEqual(source, result,
                "латинский текст обязан проходить транслитерацию БЕЗ изменений");
        }

        // ------------------------------------------------------------------ 2. КИРИЛЛИЦА

        /// <summary>
        /// КИРИЛЛИЦА ТРАНСЛИТЕРИРУЕТСЯ В ЧИТАЕМУЮ ЛАТИНИЦУ. Отчёт русскому оператору должен
        /// читаться как «Traektoriya», а не как набор знаков вопроса.
        /// </summary>
        [Test]
        public void CyrillicIsTransliteratedReadably()
        {
            string result = KvPdfWriter.Latin("Траектория");

            Assert.IsFalse(string.IsNullOrWhiteSpace(result), "результат транслитерации пуст");
            StringAssert.DoesNotContain("?", result,
                "в результате транслитерации остались знаки вопроса — текст не читается: " + result);

            // Проверяем, что это именно ЛАТИНИЦА: буквы должны попадать в ASCII.
            foreach (char c in result)
                Assert.LessOrEqual((int)c, 127,
                    "после транслитерации остался символ вне ASCII («" + c + "») в «" + result + "»");

            // И что буквы действительно латинские, а не мусор.
            StringAssert.StartsWith("T", result, "«Траектория» обязана начинаться с T: " + result);
        }

        /// <summary>
        /// ЗАГЛАВНЫЕ И СТРОЧНЫЕ РАЗЛИЧАЮТСЯ. Иначе «Робот» и «робот» дадут одинаковый текст, и в
        /// заголовках отчёта пропадёт регистр.
        /// </summary>
        [Test]
        public void CaseIsPreserved()
        {
            string upper = KvPdfWriter.Latin("РОБОТ");
            string lower = KvPdfWriter.Latin("робот");

            Assert.AreNotEqual(upper, lower,
                "заглавные и строчные буквы дали одинаковый результат — регистр потерян");
            Assert.AreEqual("ROBOT", upper, "«РОБОТ» обязано стать «ROBOT»");
        }

        // ------------------------------------------------------------------ 3. ЭКРАНИРОВАНИЕ

        /// <summary>
        /// СКОБКИ И ОБРАТНАЯ КОСАЯ ЧЕРТА ЭКРАНИРУЮТСЯ. В формате PDF эти символы — часть синтаксиса
        /// строки: неэкранированная скобка обрывает текст, и файл перестаёт открываться.
        ///
        /// Это самая частая причина «PDF не открывается» — и она возникает от обычного имени файла
        /// вроде `отчёт (2).pdf`.
        /// </summary>
        [Test]
        public void PdfSpecialCharactersAreEscaped()
        {
            string escaped = KvPdfWriter.Escape("a(b)c\\d");

            StringAssert.Contains("\\(", escaped, "открывающая скобка не экранирована: " + escaped);
            StringAssert.Contains("\\)", escaped, "закрывающая скобка не экранирована: " + escaped);
            StringAssert.Contains("\\\\", escaped, "обратная косая черта не экранирована: " + escaped);
        }

        /// <summary>
        /// ПЕРЕВОД СТРОКИ ЗАМЕНЯЕТСЯ ПРОБЕЛОМ. Перевод строки внутри строки PDF обрывает её так же,
        /// как скобка.
        /// </summary>
        [Test]
        public void NewlinesBecomeSpaces()
        {
            string escaped = KvPdfWriter.Escape("первая\nвторая\rтретья");

            Assert.IsFalse(escaped.Contains("\n"), "перевод строки не заменён");
            Assert.IsFalse(escaped.Contains("\r"), "возврат каретки не заменён");
            StringAssert.Contains(" ", escaped, "перевод строки обязан стать пробелом");
        }

        // ------------------------------------------------------------------ 4. ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ

        /// <summary>
        /// ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ: КИТАЙСКИЙ И ЯПОНСКИЙ ТЕКСТ В PDF НЕ ПЕРЕНОСИТСЯ.
        ///
        /// ЭТОТ ТЕСТ НАМЕРЕННО ФИКСИРУЕТ ДЕФЕКТ, а не требует его исправить. Встроенный шрифт PDF
        /// (`WinAnsiEncoding`) не содержит иероглифов, а транслитерация для них не определена —
        /// поэтому каждый знак становится `?`. Отчёт на китайском выйдет строкой вопросительных
        /// знаков.
        ///
        /// КАК ЗАКРЫТЬ ПО-НАСТОЯЩЕМУ: встроить TTF с CJK-глифами и перейти на кодировку Identity-H.
        /// Это замена ядра генератора, требует файла шрифта (как в 5.27) и отдельной работы.
        ///
        /// КОГДА ИСПРАВЯТ — тест покраснеет, и это правильно: он напомнит обновить отчёт и снять
        /// ограничение из списка известных.
        /// </summary>
        [Test]
        public void KnownLimitation_ChineseBecomesQuestionMarks()
        {
            string latin = KvPdfWriter.Latin("轨迹报告");
            string escaped = KvPdfWriter.Escape(latin);

            // Транслитерация иероглифы не трогает — значит дальше они попадут под замену в Escape.
            bool hasNonAscii = false;
            foreach (char c in latin)
                if (c > 126) { hasNonAscii = true; break; }

            if (!hasNonAscii)
            {
                Assert.Pass("транслитерация УЖЕ обрабатывает иероглифы — ограничение снято, " +
                            "обновите отчёт и уберите этот тест из списка известных");
            }

            Assert.IsTrue(escaped.Contains("?"),
                "ожидалось, что иероглифы станут знаками вопроса (известное ограничение), " +
                "получено: «" + escaped + "». Если ограничение сняли — обновите отчёт");

            // Фиксируем масштаб: каждый иероглиф — это один вопросительный знак.
            Assert.AreEqual(4, CountOf(escaped, '?'),
                "неверное число знаков вопроса для четырёх иероглифов: «" + escaped + "»");
        }

        private static int CountOf(string text, char symbol)
        {
            int count = 0;
            foreach (char c in text) if (c == symbol) count++;
            return count;
        }
    }
}
