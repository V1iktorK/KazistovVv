// ================================================================================================
//  KvPoseValidatorChainTests.cs — EditMode-тесты КАПСУЛЬНОЙ ЦЕПОЧКИ И ИНСТРУМЕНТА
//  (сессия S44, 30.10.2026).
//
//  ОТКУДА ЗАДАЧА. «ДЕФЕКТ 3» из §27 (карточка 5.3 плана) висел с 28.09.2026 и ни разу не
//  проверялся тестом: у SCARA длина инструмента была ЖЁСТКО НУЛЁМ (`toolDrop = 0f`), поэтому
//  четвёртый узел капсульной цепочки совпадал с третьим, и стержень инструмента не участвовал
//  ни в расчёте зазора, ни в планировании, ни в `SafetyGate`. Робот мог «проткнуть» стол
//  инструментом, и ни один зазор этого не видел.
//
//  ПОЧЕМУ ПРАВКУ ОТКЛАДЫВАЛИ. Наивное включение с `linkRadius` (6 см) ломало штатную работу
//  SCARA у столешницы: инструмент у неё опускается ниже плоскости стола, и толстая капсула
//  давала ложное пересечение. Поэтому в §27 была дана точная рекомендация: отдельная длина
//  инструмента + ТОНКИЙ радиус (≈1,2 см) вместо радиуса звена.
//
//  ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ (без сцены — на чистой геометрии):
//    1) при нулевой длине поведение ПРЕЖНЕЕ (цепочка без лишнего узла) — сцены не ломаются;
//    2) при заданной длине узел инструмента появляется и СТОИТ НА ЭТОЙ ДЛИНЕ;
//    3) радиус последнего звена — тонкий, а не радиус звена;
//    4) нулевая/отрицательная длина не создаёт вырожденного узла.
// ================================================================================================

using NUnit.Framework;
using TrajectoryCore;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Модель коллизий: есть ли инструмент в цепочке и каким радиусом он считается.</summary>
    public class KvPoseValidatorChainTests
    {
        private PoseValidator validator;

        [SetUp]
        public void SetUp()
        {
            // Валидатор создаётся как обычный объект: он не MonoBehaviour, сцена не нужна.
            validator = new PoseValidator();
        }

        // ---------------------------------------------------------------- 1. ПРЕЖНЕЕ ПОВЕДЕНИЕ

        /// <summary>
        /// ДЛИНА НОЛЬ — ИНСТРУМЕНТ НЕ УЧИТЫВАЕТСЯ, РАДИУС ЗВЕНА.
        ///
        /// Это страховка от регресса: сцены, где длину не замерили, обязаны вести себя ровно так
        /// же, как до правки. Иначе включение дефекта №3 «починило» бы одно и сломало другое —
        /// именно этого и опасались в §27.
        /// </summary>
        [Test]
        public void ZeroToolLength_KeepsPreviousBehaviour()
        {
            validator.toolLengthMeters = 0f;
            Assert.AreEqual(validator.linkRadius, validator.RadiusForLastSegment(), 1e-6f,
                "при нулевой длине инструмента радиус обязан остаться радиусом звена");
        }

        /// <summary>Отрицательная длина — тоже «инструмент не учитывать»: это ошибка ввода, а не «длинный инструмент».</summary>
        [Test]
        public void NegativeToolLength_IsIgnored()
        {
            validator.toolLengthMeters = -0.5f;
            Assert.AreEqual(validator.linkRadius, validator.RadiusForLastSegment(), 1e-6f,
                "отрицательная длина обязана читаться как «не учитывать», а не давать узел НАД рукой");
        }

        /// <summary>Совсем малая длина (меньше полмиллиметра) — шум замера, а не инструмент.</summary>
        [Test]
        public void TinyToolLength_IsIgnored()
        {
            validator.toolLengthMeters = 0.0001f;
            Assert.AreEqual(validator.linkRadius, validator.RadiusForLastSegment(), 1e-6f,
                "длина меньше 0.5 мм — это шум замера, отдельная капсула не нужна");
        }

        // ---------------------------------------------------------------- 2. ИНСТРУМЕНТ В ЦЕПОЧКЕ

        /// <summary>
        /// ЗАДАННАЯ ДЛИНА — ТОНКИЙ РАДИУС. Главное требование §27: инструмент считается СВОИМ
        /// радиусом (по умолчанию 1,2 см), а не радиусом звена (6 см). Иначе SCARA у столешницы
        /// получает ложные пересечения, и планировщик отказывает в штатной работе.
        /// </summary>
        [Test]
        public void ToolLength_UsesThinRadius()
        {
            validator.toolLengthMeters = 0.431f;                  // измеренная длина стержня SCARA
            Assert.AreEqual(validator.toolRadius, validator.RadiusForLastSegment(), 1e-6f,
                "инструмент обязан считаться своим (тонким) радиусом");
            Assert.Less(validator.toolRadius, validator.linkRadius,
                "радиус инструмента обязан быть МЕНЬШЕ радиуса звена, иначе смысл правки теряется");
            Assert.AreEqual(0.012f, validator.toolRadius, 1e-6f,
                "радиус инструмента по умолчанию — 1.2 см (реальные пальцы/игла)");
        }

        /// <summary>
        /// СТРОКА-ДОКАЗАТЕЛЬСТВО НАЗЫВАЕТ ЧИСЛО. Без неё «инструмент вне цепочки» и «всё
        /// проверено» выглядят одинаково в журнале устройства.
        /// </summary>
        [Test]
        public void DescribeChainModel_ReportsToolLengthAndRadius()
        {
            validator.toolLengthMeters = 0.25f;
            string line = validator.DescribeChainModel();

            StringAssert.Contains("инструмент", line);
            StringAssert.Contains("0.250", line, "в строке обязана быть сама длина — иначе её не проверить");
            StringAssert.Contains("радиус инструмента", line);
        }

        /// <summary>
        /// ЧТО ЗАМЕРОМ НЕ ЛОВИТСЯ — СОЗНАТЕЛЬНАЯ ГРАНИЦА. `MeasureScaraToolLength` берёт ход
        /// третьей оси из настроек контроллера; без сцены (нет `scara`) он обязан вернуть то, что
        /// задано вручную, и НЕ выдумывать геометрию.
        ///
        /// Проверяется косвенно, через публичное поведение: при отсутствии робота длина остаётся
        /// той, что задана, и никакого «само появилось 431 мм» не происходит.
        /// </summary>
        [Test]
        public void WithoutRobotScene_ToolLengthStaysAsConfigured()
        {
            validator.toolLengthMeters = 0.18f;
            validator.Init(null);                                 // робота нет — Init обязан не упасть

            Assert.IsFalse(validator.Ready, "без робота валидатор не готов — это его контракт");
            Assert.AreEqual(0.18f, validator.toolLengthMeters, 1e-6f,
                "без сцены длина инструмента обязана остаться такой, какой её задали");
        }
    }
}
