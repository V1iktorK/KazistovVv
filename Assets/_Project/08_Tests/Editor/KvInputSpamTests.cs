// ================================================================================================
//  KvInputSpamTests.cs — EditMode-тесты СПАМА НАЖАТИЙ И РЕЕСТРА КОМАНД (сессия S46).
//
//  ОТКУДА ЗАДАЧА. В шлеме оператор жмёт кнопку не один раз: контроллер дрожит в руке, луч
//  соскальзывает, палец задерживается на курке, а «двойное нажатие X» вообще задумано как
//  переключение. Поэтому реестр команд (`KvCommands`) и настройки-переключатели обязаны
//  выдерживать серию вызовов и оставаться в НАЗВАННОМ состоянии.
//
//  ЧТО БЫЛО. Реестр считал выполненные команды (`ExecutedCount`) — это единственный числовой
//  признак «кнопка сделала работу» для самопрогона интерфейса (`KvUiSweepRuntime`). При этом ни
//  один тест не проверял, что счётчик растёт РОВНО на успешные вызовы: заглушка, команда без
//  обработчика, вызов несуществующего id и упавший обработчик не должны его увеличивать.
//
//  ЧЕМ ПЛОХО БЫЛО. Счётчик, который растёт от любой попытки, превращает самопрогон в зелёную
//  печать: «команд выполнено: 3→4» печаталось бы и для кнопки, которая ничего не делает, — то
//  есть ровно для того дефекта, который самопрогон ищет.
//
//  ЧТО СТАЛО И ЧТО ЗДЕСЬ ЗАКРЕПЛЕНО:
//    1) серия вызовов переключателя не «накапливается»: чётное число возвращает исходное состояние;
//    2) `ExecutedCount` растёт на число УСПЕШНЫХ вызовов и не растёт на неуспешных;
//    3) команда-заглушка не выполняется и не считается;
//    4) повторная регистрация с тем же id ЗАМЕНЯЕТ обработчик, а не добавляет второй;
//    5) двадцать быстрых переключений настройки оставляют её выключенной;
//    6) исключение внутри обработчика не ломает реестр (поведение документировано в `KvCommands`).
//
//  ГРАНИЦА ЧЕСТНОСТИ. Здесь работают ЧИСТЫЕ функции и публичный реестр — без сцены, шлема и
//  устройства. Дребезг настоящего контроллера (PICO: несколько событий на одно нажатие) и
//  фильтрация повторов в слое ввода проверяются только на устройстве; в этом файле проверяется
//  то, что реестр обязан выдерживать любую серию вызовов.
// ================================================================================================

using System;
using System.Collections.Generic;
using KazistovVvUI;
using KazistovVvXr;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Реестр команд и переключатели: серия нажатий, счётчик, замена, падение обработчика.</summary>
    [Category(KvTestCategories.Fast)]
    public class KvInputSpamTests
    {
        /// <summary>
        /// ПРИСТАВКА К ID САМОПРОВЕРОЧНЫХ КОМАНД. Реестр статический и общий на весь прогон,
        /// поэтому id теста не имеют права совпасть с настоящими id интерфейса («point.select»).
        /// </summary>
        private const string Prefix = "selfcheck.spam.";

        private readonly List<string> registered = new List<string>(8);
        private int savedMoveMode;
        private bool hadMoveMode;
        private int savedPassthrough;
        private bool hadPassthrough;

        // ---------------------------------------------------------------- сохранение окружения
        //
        // ТЕСТ НЕ ИМЕЕТ ПРАВА МЕНЯТЬ НАСТРОЙКИ МАШИНЫ: переключатели пишут в те же PlayerPrefs,
        // из которых стартует приложение.

        [SetUp]
        public void SaveEnvironment()
        {
            hadMoveMode = PlayerPrefs.HasKey(KvXrSettings.KeyMoveMode);
            savedMoveMode = PlayerPrefs.GetInt(KvXrSettings.KeyMoveMode, 0);
            hadPassthrough = PlayerPrefs.HasKey(KvXrSettings.KeyPassthrough);
            savedPassthrough = PlayerPrefs.GetInt(KvXrSettings.KeyPassthrough, 0);
        }

        [TearDown]
        public void RestoreEnvironment()
        {
            if (hadMoveMode) PlayerPrefs.SetInt(KvXrSettings.KeyMoveMode, savedMoveMode);
            else PlayerPrefs.DeleteKey(KvXrSettings.KeyMoveMode);
            if (hadPassthrough) PlayerPrefs.SetInt(KvXrSettings.KeyPassthrough, savedPassthrough);
            else PlayerPrefs.DeleteKey(KvXrSettings.KeyPassthrough);
            PlayerPrefs.Save();

            // У реестра нет удаления команды, поэтому свои команды ЗАМЕНЯЕМ пустышками: иначе
            // бросающий исключение обработчик остался бы в общем реестре до конца прогона.
            foreach (string id in registered)
                KvCommands.Register(new KvCommand { Id = id, Title = "самопроверка (снята)", Execute = null });
            registered.Clear();
        }

        /// <summary>Зарегистрировать самопроверочную команду и запомнить её id для уборки.</summary>
        private string Register(Action execute, bool stub = false)
        {
            string id = Prefix + Guid.NewGuid().ToString("N");
            KvCommands.Register(new KvCommand
            {
                Id = id,
                Title = "самопроверка",
                Description = "команда, созданная тестом",
                Execute = execute,
                Stub = stub
            });
            registered.Add(id);
            return id;
        }

        // ==================================================== 1. СЕРИЯ НАЖАТИЙ

        /// <summary>
        /// СЕРИЯ ИЗ ДЕСЯТИ ВЫЗОВОВ ПЕРЕКЛЮЧАТЕЛЯ НЕ НАКАПЛИВАЕТСЯ: чётное число возвращает исходное
        /// состояние.
        ///
        /// ЧТО БЫЛО. Переключатель по определению меняет состояние на противоположное; ошибка
        /// «переключение в одну сторону» (сравнение значения с самим собой) выглядит как рабочая
        /// кнопка, которая на самом деле ничего не меняет.
        ///
        /// ЧЕМ ПЛОХО. Оператор жмёт «переключить» десять раз (дрожащей рукой — это норма в шлеме)
        /// и получает состояние, которое зависит от чётности, а не от того, что он хотел.
        ///
        /// ЧТО СТАЛО. Проверяются ОБА свойства: один вызов состояние МЕНЯЕТ, десять вызовов
        /// возвращают исходное. Одно без другого бессмысленно.
        /// </summary>
        [Test]
        public void TenInvocationsOfToggleMatchItsEvenNumberOfClicks()
        {
            int runs = 0;
            bool state = false;
            string id = Register(delegate { runs++; state = !state; });

            int countBefore = KvCommands.ExecutedCount;

            Assert.IsTrue(KvCommands.Invoke(id), "вызов зарегистрированной команды вернул false");
            Assert.AreEqual(1, runs, "обработчик не вызван ни разу");
            Assert.IsTrue(state, "первый вызов переключателя не изменил состояние — кнопка «щелкает», " +
                                 "ничего не меняя");

            for (int i = 0; i < 9; i++)
                Assert.IsTrue(KvCommands.Invoke(id), "вызов №" + (i + 2) + " вернул false");

            Assert.AreEqual(10, runs, "десять вызовов дали " + runs + " выполнений обработчика");
            Assert.IsFalse(state,
                "десять вызовов переключателя (чётное число) оставили состояние включённым: серия " +
                "нажатий накапливается, и итог зависит от чётности, а не от намерения оператора");

            // ДОКУМЕНТИРОВАННОЕ ПРАВИЛО: каждый УСПЕШНЫЙ вызов считается, даже если состояние
            // вернулось к исходному. Это то, на что опирается самопрогон интерфейса.
            Assert.AreEqual(countBefore + 10, KvCommands.ExecutedCount,
                "десять успешных вызовов не дали +10 к `ExecutedCount` — самопрогон интерфейса " +
                "не увидит работы кнопки");
        }

        // ==================================================== 2. СЧЁТЧИК ВЫПОЛНЕННЫХ

        /// <summary>
        /// `ExecutedCount` РАСТЁТ РОВНО НА ЧИСЛО УСПЕШНЫХ ВЫЗОВОВ.
        ///
        /// ЧТО БЫЛО. Счётчик — единственный машинный признак «кнопка сделала работу». Если он
        /// растёт от вызова несуществующего id или от недоступной команды, признак перестаёт
        /// что-либо значить.
        ///
        /// ЧЕМ ПЛОХО. Самопрогон печатает «команд выполнено: 3→4» и для кнопки, которая на самом
        /// деле ничего не делает, — то есть зеленит ровно тот дефект, который ищет.
        ///
        /// ЧТО СТАЛО. Прирост сверяется по дельте: десять успешных вызовов — ровно +10,
        /// несуществующий id — ровно +0.
        /// </summary>
        [Test]
        public void ExecutedCountGrowsExactlyBySuccessfulCalls()
        {
            int runs = 0;
            string id = Register(delegate { runs++; });

            int before = KvCommands.ExecutedCount;
            for (int i = 0; i < 10; i++)
                Assert.IsTrue(KvCommands.Invoke(id), "вызов №" + (i + 1) + " вернул false");

            Assert.AreEqual(10, runs, "обработчик выполнен " + runs + " раз вместо десяти");
            Assert.AreEqual(before + 10, KvCommands.ExecutedCount,
                "десять успешных вызовов дали прирост " + (KvCommands.ExecutedCount - before) +
                " вместо 10 — самопрогон интерфейса считает работу по этому числу");

            // НЕСУЩЕСТВУЮЩИЙ ID: возвращает false и счётчик не трогает.
            string missing = Prefix + "нет.такой." + Guid.NewGuid().ToString("N");
            Assert.IsNull(KvCommands.Get(missing), "`Get` нашёл команду, которой не регистрировали");

            int afterKnown = KvCommands.ExecutedCount;
            Assert.IsFalse(KvCommands.Invoke(missing),
                "вызов несуществующего id вернул true — вызывающий уверен, что команда сработала");
            Assert.AreEqual(afterKnown, KvCommands.ExecutedCount,
                "счётчик вырос на вызов НЕСУЩЕСТВУЮЩЕЙ команды: цифра «команд выполнено» перестала " +
                "означать выполненную работу");

            // АНТИ-ВАКУУМ: счётчик вообще умеет расти (иначе +0 выше выполнялось бы всегда).
            KvCommands.Invoke(id);
            Assert.AreEqual(afterKnown + 1, KvCommands.ExecutedCount,
                "счётчик не растёт даже на успешном вызове — дельта процесса бессмысленна");
        }

        // ==================================================== 3. ЗАГЛУШКА

        /// <summary>
        /// КОМАНДА-ЗАГЛУШКА (`Stub = true`) НЕ ВЫПОЛНЯЕТСЯ, ВОЗВРАЩАЕТ false И НЕ СЧИТАЕТСЯ.
        ///
        /// ЧТО БЫЛО. Заглушка — это «кнопка есть, функционала нет». Такие команды регистрируются
        /// намеренно и потом перекрываются реальными обработчиками (`FeatureHub`), поэтому важно,
        /// чтобы до перекрытия они честно ничего не делали.
        ///
        /// ЧЕМ ПЛОХО. Заглушка, которая «выполняется», даёт ложный признак работы сразу в двух
        /// местах: в счётчике самопрогона и в журнале («команда выполнена»).
        ///
        /// ЧТО СТАЛО. Недоступная команда не выполняет обработчик, не увеличивает счётчик и
        /// возвращает false; та же команда БЕЗ флага — выполняется (анти-вакуум).
        /// </summary>
        [Test]
        public void StubCommandReturnsFalseAndIsNotCounted()
        {
            int runs = 0;
            string id = Register(delegate { runs++; }, true);

            Assert.IsTrue(KvCommands.Get(id).Stub, "подготовка сорвана: команда зарегистрирована без флага Stub");
            Assert.IsFalse(KvCommands.IsEnabled(id), "команда-заглушка считается доступной — интерфейс " +
                                                    "покажет её рабочей");

            int before = KvCommands.ExecutedCount;
            Assert.IsFalse(KvCommands.Invoke(id),
                "вызов команды-заглушки вернул true — вызывающий уверен, что работа сделана");
            Assert.AreEqual(0, runs, "заглушка ВЫПОЛНИЛА обработчик, хотя функционала у неё нет");
            Assert.AreEqual(before, KvCommands.ExecutedCount,
                "заглушка засчитана выполненной — счётчик «команд выполнено» начнёт врать");

            // АНТИ-ВАКУУМ: тот же id без флага Stub ведёт себя как рабочая команда.
            KvCommands.Register(new KvCommand
            {
                Id = id,
                Title = "уже не заглушка",
                Execute = delegate { runs++; }
            });

            int beforeWorking = KvCommands.ExecutedCount;
            Assert.IsTrue(KvCommands.Invoke(id), "команда без флага Stub не выполнилась");
            Assert.AreEqual(1, runs, "обработчик рабочей команды не вызван");
            Assert.AreEqual(beforeWorking + 1, KvCommands.ExecutedCount,
                "рабочая команда не увеличила счётчик — тогда различие «заглушка/работа» не проверяемо");
        }

        // ==================================================== 4. ПОВТОРНАЯ РЕГИСТРАЦИЯ

        /// <summary>
        /// ПОВТОРНАЯ РЕГИСТРАЦИЯ С ТЕМ ЖЕ ID ЗАМЕНЯЕТ ОБРАБОТЧИК, А НЕ ДОБАВЛЯЕТ ВТОРОЙ.
        ///
        /// ЧТО БЫЛО. `KvCommands.Register` при совпадении id заменяет команду — на этом стоит вся
        /// схема «заглушка → реальный обработчик» (`FeatureHub` перерегистрирует `edit.undo`,
        /// `file.export` и другие).
        ///
        /// ЧЕМ ПЛОХО. Если бы регистрация добавляла вторую запись, кнопка в тулбаре появлялась бы
        /// дважды, а вызов выполнял бы ОБА обработчика — то есть работу делали бы дважды (двойной
        /// экспорт, двойной пуск). Заметить это в интерфейсе трудно: обе кнопки выглядят одинаково.
        ///
        /// ЧТО СТАЛО. После перерегистрации в реестре остаётся ровно одна запись с этим id, и
        /// вызывается ТОЛЬКО новый обработчик (проверяется счётчиками в тесте).
        /// </summary>
        [Test]
        public void ReregisteringSameIdReplacesHandler()
        {
            int firstHandler = 0;
            int secondHandler = 0;

            string id = Register(delegate { firstHandler++; });
            int sizeBefore = KvCommands.All.Count;

            KvCommands.Register(new KvCommand
            {
                Id = id,
                Title = "второй обработчик",
                Execute = delegate { secondHandler++; }
            });

            Assert.AreEqual(sizeBefore, KvCommands.All.Count,
                "повторная регистрация ДОБАВИЛА команду: кнопка появится в тулбаре дважды, и одна " +
                "из них будет вести себя иначе, чем другая");

            int withSameId = 0;
            foreach (KvCommand command in KvCommands.All)
                if (command != null && command.Id == id) withSameId++;
            Assert.AreEqual(1, withSameId, "в реестре " + withSameId + " команд с одним id «" + id + "»");

            KvCommands.Invoke(id);
            Assert.AreEqual(0, firstHandler,
                "после перерегистрации вызван СТАРЫЙ обработчик — замены не произошло, и работа " +
                "выполняется не тем кодом, который зарегистрирован последним");
            Assert.AreEqual(1, secondHandler, "новый обработчик не вызван ни разу");
        }

        // ==================================================== 5. БЫСТРАЯ СЕРИЯ ПЕРЕКЛЮЧЕНИЙ

        /// <summary>
        /// ДВАДЦАТЬ БЫСТРЫХ «ВКЛЮЧИТЬ/ВЫКЛЮЧИТЬ» ОСТАВЛЯЮТ НАСТРОЙКУ ВЫКЛЮЧЕННОЙ.
        ///
        /// ЧТО БЫЛО. Переключатели в шлеме (`KvXrSettings.ToggleMoveMode`, `KvXrSettings.ToggleMode`)
        /// вызываются двойным нажатием кнопки и из панели — то есть могут прийти серией.
        ///
        /// ЧЕМ ПЛОХО. Если переключение «залипает» (например, читает устаревшее значение из кэша),
        /// чётная серия оставляет режим не тем, который был: оператор дважды жмёт «обратно»,
        /// а режим уезжает дальше.
        ///
        /// ЧТО СТАЛО. После 20 переключений состояние равно исходному, а одно переключение его
        /// меняет — оба факта вместе и означают «переключатель работает и не залипает».
        /// </summary>
        [Test]
        public void TwentyQuickTogglesLeaveSettingAtStartingState()
        {
            // --- способ перемещения
            KvXrSettings.SetMoveMode(KvXrMoveMode.Teleport);
            KvXrMoveMode start = KvXrSettings.GetMoveMode();
            Assert.AreEqual(KvXrMoveMode.Teleport, start, "подготовка сорвана: способ перемещения не задался");

            for (int i = 0; i < 20; i++)
            {
                KvXrMoveMode next = KvXrSettings.ToggleMoveMode();
                Assert.AreEqual(KvXrSettings.GetMoveMode(), next,
                    "переключатель вернул «" + next + "», а настройка стала «" +
                    KvXrSettings.GetMoveMode() + "» — возвращаемое значение врёт о состоянии");
            }

            Assert.AreEqual(start, KvXrSettings.GetMoveMode(),
                "двадцать переключений (чётное число) оставили способ перемещения ПЕРЕКЛЮЧЁННЫМ: " +
                "серия нажатий не сходится, и оператор не может вернуться к исходному режиму");

            // АНТИ-ВАКУУМ: одно переключение состояние меняет.
            Assert.AreNotEqual(start, KvXrSettings.ToggleMoveMode(),
                "переключатель способа перемещения вообще не переключает — тогда чётность выше " +
                "выполнялась бы и на мёртвой кнопке");

            // --- режим VR / MR
            KvXrSettings.SetModeIndex(KvXrSettings.ModeVr);
            for (int i = 0; i < 20; i++) KvXrSettings.ToggleMode();

            Assert.AreEqual(KvXrSettings.ModeVr, KvXrSettings.GetModeIndex(),
                "двадцать переключений режима оставили приложение в MR — при том что решение " +
                "владельца «запуск всегда в VR» и подпись «применится после перезапуска»");

            Assert.AreEqual(KvXrSettings.ModeMr, KvXrSettings.ToggleMode(),
                "переключатель режима VR/MR не переключает — проверка чётности бессмысленна");
        }

        // ==================================================== 6. ПАДЕНИЕ ОБРАБОТЧИКА

        /// <summary>
        /// ИСКЛЮЧЕНИЕ ВНУТРИ ОБРАБОТЧИКА НЕ ЛОМАЕТ РЕЕСТР, но и не считается успехом.
        ///
        /// ЧТО БЫЛО. `KvCommands.Invoke` вызывает обработчик напрямую и увеличивает счётчик ПОСЛЕ
        /// вызова. Поведение документировано в самом реестре: «упавшая команда тоже не считается:
        /// до счётчика дело не доходит».
        ///
        /// ЧЕМ ПЛОХО. Если бы падение оставляло реестр в испорченном состоянии, одна сломанная
        /// команда уносила бы с собой весь интерфейс: следующие кнопки переставали бы работать, и
        /// причина была бы не в них.
        ///
        /// ЧТО СТАЛО (и что закреплено здесь):
        ///   1) исключение выходит наружу — вызывающий узнаёт о поломке, а не получает «успех»;
        ///   2) `ExecutedCount` НЕ растёт: упавшая команда работу не выполнила;
        ///   3) реестр цел: та же команда на месте, соседняя выполняется нормально;
        ///   4) недоступная команда (Stub) до обработчика не доходит вовсе.
        ///
        /// ОТДЕЛЬНО В ОТЧЁТЕ: реестр НЕ перехватывает исключения обработчиков — исключение уходит
        /// в вызывающий код (в интерфейсе это обработчик нажатия uGUI). Для кнопки это означает
        /// «кадр нажатия сорван», и стоит решить владельцу, нужен ли здесь `try/catch` с записью
        /// в журнал. Тест ниже фиксирует ТЕКУЩЕЕ документированное поведение, а не выдаёт его
        /// за желаемое.
        /// </summary>
        [Test]
        public void HandlerExceptionDoesNotBreakTheRegistry()
        {
            int healthyRuns = 0;
            string broken = Register(delegate
            {
                throw new InvalidOperationException("самопроверка: падение обработчика команды");
            });
            string healthy = Register(delegate { healthyRuns++; });

            int before = KvCommands.ExecutedCount;

            Assert.Throws<InvalidOperationException>(delegate { KvCommands.Invoke(broken); },
                "падение внутри обработчика проглочено: вызывающий считает, что команда выполнена, " +
                "а на экране ничего не произошло");

            Assert.AreEqual(before, KvCommands.ExecutedCount,
                "упавшая команда засчитана выполненной (счётчик +" +
                (KvCommands.ExecutedCount - before) + ") — самопрогон увидит работу, которой нет");

            Assert.IsNotNull(KvCommands.Get(broken), "после исключения команда исчезла из реестра");

            // РЕЕСТР ЦЕЛ: соседняя команда выполняется нормально и считается.
            Assert.IsTrue(KvCommands.Invoke(healthy),
                "после падения соседней команды следующая не выполнилась — одна сломанная кнопка " +
                "уносит весь интерфейс");
            Assert.AreEqual(1, healthyRuns, "соседняя команда не дошла до обработчика");
            Assert.AreEqual(before + 1, KvCommands.ExecutedCount,
                "после падения соседней команды счётчик не вырос на её успешный вызов");

            // И САМА СЛОМАННАЯ команда остаётся вызываемой: реестр не «выключил» её молча.
            Assert.IsTrue(KvCommands.IsEnabled(broken),
                "после падения команда стала недоступной без объяснения — оператор увидит серую " +
                "кнопку и не узнает причину");
        }

        // ==================================================== 7. КОМАНДА БЕЗ ОБРАБОТЧИКА

        /// <summary>
        /// ДОСТУПНАЯ КОМАНДА БЕЗ ОБРАБОТЧИКА НЕ СЧИТАЕТСЯ ВЫПОЛНЕННОЙ.
        ///
        /// ЧТО БЫЛО. Пока id не перекрыт реальным обработчиком, команда может быть зарегистрирована
        /// с `Execute = null`: она доступна (не заглушка), но работы не делает.
        ///
        /// ЧЕМ ПЛОХО. Если такая команда попадает в счётчик, самопрогон интерфейса отчитывается
        /// «сработало» ровно там, где кнопка пустая.
        ///
        /// ЧТО СТАЛО. `Invoke` возвращает true (команда доступна), но `ExecutedCount` не растёт:
        /// «доступна» и «сделала работу» — разные вещи, и это записано в самом реестре.
        /// </summary>
        [Test]
        public void CommandWithoutHandlerIsNotCounted()
        {
            string id = Register(null);

            Assert.IsTrue(KvCommands.IsEnabled(id),
                "команда без обработчика считается недоступной — по документации реестра она " +
                "доступна, просто ничего не делает");

            int before = KvCommands.ExecutedCount;
            Assert.IsTrue(KvCommands.Invoke(id), "вызов доступной команды вернул false");

            Assert.AreEqual(before, KvCommands.ExecutedCount,
                "команда БЕЗ обработчика засчитана выполненной — самопрогон увидит «работу», которой нет");
        }
