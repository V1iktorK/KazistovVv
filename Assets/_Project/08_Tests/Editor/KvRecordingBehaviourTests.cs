// ================================================================================================
//  KvRecordingBehaviourTests.cs — ПОВЕДЕНЧЕСКИЕ тесты папки `01_Scripts\Recording` (P4-8).
//
//  ОТКУДА ЗАДАЧА. Запись траектории (`KvRecordingService`) и её файл (`KvTrajectoryRecord`) не
//  имели тестов поведения: то, что про них было, проверяло исходник поиском строк. Опаснее всего
//  это для ПУСТОЙ и БИТОЙ записи: там ошибка не видна в работе (робот просто «не едет»), зато
//  хорошо видна оператору как «запись не сохранилась и причину не сказали».
//
//  ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ (без сцены и без диска):
//    1) пустая запись не превращается в траекторию и не сохраняется;
//    2) порог «двух сэмплов» живёт в ОДНОМ месте — им пользуются сохранение и воспроизведение;
//    3) безымянная запись получает УНИКАЛЬНОЕ имя с меткой времени;
//    4) `Normalize` чинит битую запись (пустые сэмплы, немонотонное время, нулевую длительность);
//    5) длина пути считается по TCP-точкам.
//
//  ГРАНИЦА ЧЕСТНОСТИ: `StartRecording`/`Play` требуют привязанного потока с готовым роботом — в
//  EditMode его нет, поэтому проверяется РЕШАЮЩАЯ часть (имя, порог, отказ сохранять) — та самая,
//  из-за которой запись терялась молча.
// ================================================================================================

using KazistovVvFeatures;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Поведение записи траектории: пустая запись, имя, починка файла.</summary>
    [Category(KvTestCategories.Fast)]
    public class KvRecordingBehaviourTests
    {
        /// <summary>Сэмпл записи с заданным временем, позой и точкой TCP.</summary>
        private static KvRecordSample Sample(float t, float x, float q = 0f)
        {
            return new KvRecordSample
            {
                t = t,
                q = new[] { q, q, q },
                tcp = new[] { x, 0f, 0f }
            };
        }

        /// <summary>
        /// ПУСТАЯ ЗАПИСЬ НЕ СТАНОВИТСЯ ТРАЕКТОРИЕЙ. Главная защита от «файл есть, но пустой».
        ///
        /// ПОЧЕМУ ЭТО ВАЖНО. `ToPlannedTrajectory` — единственный путь, которым запись отдаётся
        /// фантому и исполнителю. Если для записи без сэмплов он вернёт «план» из нуля точек, дальше
        /// по течению будет либо `IndexOutOfRangeException` в цикле движения, либо робот, который
        /// «поехал по пустой траектории». Поэтому пустая запись обязана честно вернуть `null`.
        /// </summary>
        [Test]
        public void EmptyRecord_HasNoSamplesAndNoTrajectory()
        {
            var record = new KvTrajectoryRecord();

            Assert.AreEqual(0, record.SampleCount, "у новой записи не должно быть сэмплов");
            Assert.AreEqual(0, record.Dof, "у записи без сэмплов число осей неизвестно — это 0, а не «шесть»");
            Assert.IsNull(record.ToPlannedTrajectory(),
                "пустая запись превратилась в траекторию — исполнителю нечего проигрывать, " +
                "а он получит план из нуля точек");
            Assert.IsNotNull(record.samples, "список сэмплов обязан быть, а не null");
        }

        /// <summary>
        /// СЛИШКОМ КОРОТКАЯ ЗАПИСЬ НЕ СОХРАНЯЕТСЯ — и НЕ ТРОГАЕТ ДИСК.
        ///
        /// ПОЧЕМУ ЭТОТ ТЕСТ ВАЖЕН ДЛЯ ОПЕРАТОРА. Запись из одного сэмпла — это не движение, а точка:
        /// воспроизводить нечего, путь нулевой. Такая запись не должна появляться в списке моделей:
        /// оператор выбрал бы её и не понял, почему робот не едет.
        ///
        /// Файл НЕ создаётся: метод обязан выйти ДО обращения к диску (проверяем по пустому пути).
        /// </summary>
        [Test]
        public void ShortRecord_IsNotSavedAndKeepsNoFilePath()
        {
            var record = new KvTrajectoryRecord { name = "Короткая" };
            record.samples.Add(Sample(0f, 0f));

            Assert.IsNull(KvRecordStore.Save(record),
                "запись из одного сэмпла сохранилась — в списке моделей появится «пустая» запись");
            Assert.IsEmpty(record.filePath,
                "у несохранённой записи появился путь к файлу — значит диск всё-таки тронули");
        }

        /// <summary>
        /// ПОРОГ «ХВАТИТ СЭМПЛОВ» ЖИВЁТ В ОДНОМ МЕСТЕ. Им пользуются сохранение, воспроизведение и
        /// загрузка с диска; если одна из веток заведёт своё число, запись из одного сэмпла пройдёт
        /// в одном месте и будет отвергнута в другом — ровно тот класс дефекта «в одном месте
        /// работает, в другом нет».
        /// </summary>
        [Test]
        public void SampleThresholdIsShared()
        {
            Assert.IsFalse(KvRecordingService.HasEnoughSamples(0), "ноль сэмплов — не запись");
            Assert.IsFalse(KvRecordingService.HasEnoughSamples(1), "один сэмпл — точка, а не движение");
            Assert.IsTrue(KvRecordingService.HasEnoughSamples(2), "два сэмпла — уже отрезок, запись годна");
            Assert.IsTrue(KvRecordingService.HasEnoughSamples(250), "длинная запись годна");
        }

        /// <summary>
        /// БЕЗЫМЯННАЯ ЗАПИСЬ ПОЛУЧАЕТ ИМЯ С МЕТКОЙ ВРЕМЕНИ.
        ///
        /// ЧТО ЛОВИТ. Пустое имя раньше заменялось на «Запись» без времени: два прогона подряд с
        /// пустым полем давали ОДИНАКОВОЕ имя, а файл — один на двоих. Вторая запись затирала
        /// первую, и оператор терял только что сделанный дубль, не понимая, куда он делся.
        /// Метка времени — параметр, поэтому проверка не зависит ни от часов, ни от диска.
        /// </summary>
        [Test]
        public void EmptyNameGetsUniqueNameWithTimeStamp()
        {
            string first = KvRecordingService.BuildName("", "2026-11-12_10-00-00");
            string second = KvRecordingService.BuildName(null, "2026-11-12_10-00-01");

            StringAssert.StartsWith("Запись ", first, "безымянная запись обязана получить осмысленное имя");
            StringAssert.Contains("2026-11-12_10-00-00", first,
                "в имени нет метки времени — вторая запись с тем же именем затрёт первую");
            Assert.AreNotEqual(first, second,
                "две записи в разное время получили ОДИНАКОВОЕ имя — вторая затрёт первую");

            Assert.AreEqual("Обед", KvRecordingService.BuildName("Обед", "2026-11-12_10-00-00"),
                "введённое оператором имя обязано сохраняться ДОСЛОВНО, без приставок");
        }

        /// <summary>
        /// `NORMALIZE` ЧИНИТ БИТУЮ ЗАПИСЬ: выбрасывает пустые сэмплы, делает время монотонным,
        /// заполняет длительность и длину пути.
        ///
        /// ПОЧЕМУ ЭТО НУЖНО. Файл записи — обычный JSON в данных приложения: его правят руками,
        /// его может оставить прерванный прогон. Запись с пустым `q` роняет построение траектории
        /// (`q.Length` нулевой → поза не той длины), а время, идущее назад, ломает и скорость, и
        /// предохранитель. `Normalize` вызывается после чтения и после остановки записи — значит
        /// именно она обязана привести файл в согласованный вид.
        /// </summary>
        [Test]
        public void RecordNormalizeRepairsBrokenSamplesAndTime()
        {
            var record = new KvTrajectoryRecord { name = "", rate = 0f, speed = 0f };
            record.samples.Add(Sample(0.5f, 0f));
            record.samples.Add(null);                                    // битый элемент списка
            record.samples.Add(new KvRecordSample { t = 0.9f, q = new float[0] });  // пустая поза
            record.samples.Add(Sample(0.2f, 1f));                        // время НАЗАД

            record.Normalize();

            Assert.AreEqual(2, record.SampleCount,
                "после починки должны остаться только сэмплы с непустой позой");
            Assert.AreEqual(0.5f, record.samples[0].t, 1e-6f, "первый сэмпл остаётся на своём времени");
            Assert.AreEqual(0.5f, record.samples[1].t, 1e-6f,
                "время пошло назад — починка обязана выровнять его по предыдущему, а не оставить " +
                "убывающим (иначе предохранитель увидит «время назад» на ровном месте)");
            Assert.AreEqual(0.5f, record.duration, 1e-6f,
                "длительность обязана быть равна времени последнего сэмпла");
            Assert.AreEqual(1f, record.length, 1e-6f,
                "длина пути обязана посчитаться по TCP-точкам, а не остаться нулевой");
            Assert.AreEqual(20f, record.rate, 1e-6f, "нулевая частота записи — это дефект файла: 20 Гц по умолчанию");
            Assert.AreEqual(1f, record.speed, 1e-6f, "нулевой множитель скорости дал бы «стоячее» воспроизведение");
            Assert.IsNotEmpty(record.name, "у записи без имени обязано появиться имя по умолчанию");
            Assert.IsNotEmpty(record.id, "у записи обязан быть идентификатор — иначе файлы не различить");
        }
    }
}
