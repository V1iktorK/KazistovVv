//
//  ОТКУДА ЗАДАЧА. `Trajectory\PostureControl.cs` лежал «в стол»: класс НЕ ВЫЗЫВАЕТСЯ НИ ОТКУДА.
//  Пункт 5.24 плана ставил развилку: подключить или удалить.
//
//  ГЛАВНАЯ ЧАСТЬ, КОТОРУЮ МОЖНО ПРОВЕРИТЬ БЕЗ СЦЕНЫ, — РЕШЕНИЕ СИСТЕМЫ 3×3.
//  Вся математика постуры опирается на `A y = e`, где `A = J Jᵀ + λ²I` — маленькая симметричная
//  система. Ошибка в ней НЕ видна снаружи: робот всё равно поедет, просто не туда, и виноватой
//  окажется «траектория». Поэтому здесь проверяется именно решение — на матрицах с ответом,
//  который считается в уме.
//
//  ЭТО НЕ «ТЕСТ РАДИ ТЕСТА»: `PostureControl.Solve3` был публично недоступен, и его поведение при
//  вырожденной матрице (сингулярность!) не проверялось ничем. Вырожденная матрица — это ровно
//  сингулярная конфигурация робота, то есть самый частый источник бед в этом проекте.
// ================================================================================================

using System;
using System.Reflection;
using NUnit.Framework;
using TrajectoryCore;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Решение системы 3×3 внутри постура-контроля.</summary>
    public class KvPostureControlTests
    {
        /// <summary>
        /// ВЫЗОВ `Solve3` — ЕДИНСТВЕННОЕ МЕСТО С ОТРАЖЕНИЕМ, и оно ПАДАЕТ, а не пропускается.
        ///
        /// ПОЧЕМУ ОТРАЖЕНИЕ ВООБЩЕ. Метод сделан `private static` в исходнике (это разумно: наружу
        /// ему выходить незачем). Если его переименуют, тест обязан ПОКРАСНЕТЬ, а не выключиться —
        /// урок E-16: «Assert.Ignore вместо падения» уже один раз превратил 13 тестов в декорацию.
        /// </summary>
        private static Func<double[,], double[], Tuple<bool, double[]>> Solve3Caller()
        {
            MethodInfo m = typeof(PostureControl).GetMethod(
                "Solve3", BindingFlags.NonPublic | BindingFlags.Static);
            Assert.IsNotNull(m,
                "PostureControl.Solve3 не найден — внутренний API изменился. Это КРАСНЫЙ тест, " +
                "а не пропуск: переименование метода делает всю математику постуры непроверяемой (E-16)");
            return delegate (double[,] a, double[] b)
            {
                object[] args = { a, b, null };
                object result = m.Invoke(null, args);
                return Tuple.Create((bool)result, (double[])args[2]);
            };
        }

        // ---------------------------------------------------------------- 1. ЕДИНИЧНАЯ МАТРИЦА

        /// <summary>
        /// ЕДИНИЧНАЯ МАТРИЦА: решение равно правой части. Проверка «ответ очевиден» — если метод
        /// ошибается даже здесь, дальше смотреть нечего.
        /// </summary>
        [Test]
        public void Solve3_IdentityMatrix_ReturnsRightHandSide()
        {
            var a = new double[,] { { 1, 0, 0 }, { 0, 1, 0 }, { 0, 0, 1 } };
            var b = new double[] { 2.0, -3.0, 0.5 };

            var r = Solve3Caller()(a, b);
            Assert.IsTrue(r.Item1, "система с единичной матрицей обязана решаться");

            Assert.AreEqual(2.0, r.Item2[0], 1e-9);
            Assert.AreEqual(-3.0, r.Item2[1], 1e-9);
            Assert.AreEqual(0.5, r.Item2[2], 1e-9);
        }

        // ---------------------------------------------------------------- 2. ДИАГОНАЛЬ

        /// <summary>
        /// ДИАГОНАЛЬНАЯ матрица — решение `b[i] / a[i]`. Это ровно случай «оси независимы»,
        /// часто встречающийся у SCARA в вытянутой конфигурации.
        /// </summary>
        [Test]
        public void Solve3_DiagonalMatrix_ScalesEachComponent()
        {
            var a = new double[,] { { 2, 0, 0 }, { 0, 4, 0 }, { 0, 0, 0.5 } };
            var b = new double[] { 4.0, 8.0, 1.0 };

            var r = Solve3Caller()(a, b);
            Assert.IsTrue(r.Item1);
            Assert.AreEqual(2.0, r.Item2[0], 1e-9, "4 / 2 = 2");
            Assert.AreEqual(2.0, r.Item2[1], 1e-9, "8 / 4 = 2");
            Assert.AreEqual(2.0, r.Item2[2], 1e-9, "1 / 0,5 = 2");
        }

        // ---------------------------------------------------------------- 3. НЕДИАГОНАЛЬНАЯ

        /// <summary>
        /// СИММЕТРИЧНАЯ МАТРИЦА С НЕНУЛЕВЫМИ ВНЕДИАГОНАЛЬНЫМИ — самое ценное: проверяется, что
        /// метод не «забыл» перекрёстные члены. Система подобрана так, что ответ — целые числа.
        ///
        /// Матрица [[2,1,0],[1,2,1],[0,1,2]] и правая часть [3,4,3] дают ровно [1,1,1]:
        ///   2·1 + 1·1 + 0·1 = 3 ✓;  1·1 + 2·1 + 1·1 = 4 ✓;  0·1 + 1·1 + 2·1 = 3 ✓
        /// Подстановка проверяема в уме, а не «доверься отчёту».
        /// </summary>
        [Test]
        public void Solve3_SymmetricTridiagonal_ResolvesCrossTerms()
        {
            var a = new double[,] { { 2, 1, 0 }, { 1, 2, 1 }, { 0, 1, 2 } };
            var b = new double[] { 3.0, 4.0, 3.0 };

            var r = Solve3Caller()(a, b);
            Assert.IsTrue(r.Item1);

            Assert.AreEqual(1.0, r.Item2[0], 1e-9);
            Assert.AreEqual(1.0, r.Item2[1], 1e-9);
            Assert.AreEqual(1.0, r.Item2[2], 1e-9);

            // Подстановка результата обратно в уравнение — независимая проверка, а не сверка с
            // ожиданием в том же коде: если Solve3 и подстановка ошибочны одинаково, это сломается.
            for (int row = 0; row < 3; row++)
            {
                double sum = 0;
                for (int col = 0; col < 3; col++) sum += a[row, col] * r.Item2[col];
                Assert.AreEqual(b[row], sum, 1e-9,
                    "подстановка не сходится в строке " + row + ": " + sum.ToString("0.0000"));
            }
        }

        // ---------------------------------------------------------------- 4. СИНГУЛЯРНОСТЬ

        /// <summary>
        /// ВЫРОЖДЕННАЯ МАТРИЦА (определитель ноль) — ОТКАЗ, а не мусор.
        ///
        /// ПОЧЕМУ ЭТО ГЛАВНАЯ ПРОВЕРКА ФАЙЛА. Вырожденная `A = J Jᵀ` — это РОВНО сингулярная
        /// конфигурация робота (оси вытянуты в линию). Если метод «решит» такую систему, он выдаст
        /// гигантские шаги по суставам. Поэтому правильный ответ — `false`, и вызывающий код
        /// (см. `Step`) оставляет позу как есть.
        ///
        /// Тест ловит классическую ошибку: забытый порог на определитель. Без него деление на
        /// почти-ноль даёт 1e+16 градусов, и робот «телепортируется».
        /// </summary>
        [Test]
        public void Solve3_SingularMatrix_RefusesInsteadOfProducingGarbage()
        {
            // Строки 1 и 3 пропорциональны → определитель ноль.
            var a = new double[,] { { 1, 2, 3 }, { 2, 4, 6 }, { 1, 1, 1 } };
            var b = new double[] { 1.0, 2.0, 3.0 };

            var r = Solve3Caller()(a, b);
            Assert.IsFalse(r.Item1,
                "для вырожденной матрицы решение обязано ОТКАЗАТЬ: это сингулярная поза робота, " +
                "и любой «ответ» будет шагом на миллионы градусов");
        }

        /// <summary>
        /// ПОЧТИ ВЫРОЖДЕННАЯ (определитель 1e-9) тоже отказ — иначе получаются шаги в миллионы
        /// градусов, которые выглядят как «робота дёрнуло».
        /// </summary>
        [Test]
        public void Solve3_NearSingularMatrix_Refuses()
        {
            var a = new double[,] { { 1, 0, 0 }, { 0, 1, 0 }, { 0, 0, 1e-9 } };
            var b = new double[] { 1.0, 1.0, 1.0 };

            var r = Solve3Caller()(a, b);
            Assert.IsFalse(r.Item1, "матрица с определителем 1e-9 обязана отвергаться");
        }

        // ---------------------------------------------------------------- 5. ЧИСЛО ОБУСЛОВЛЕННОСТИ

        /// <summary>
        /// ХОРОШО ОБУСЛОВЛЕННАЯ МАТРИЦА РЕШАЕТСЯ ТОЧНО. Промежуточный случай между «единичной» и
        /// «вырожденной»: проверяется, что порог не отвергает нормальные конфигурации. Иначе
        /// постура перестанет работать в обычных позах, и это будет выглядеть как «перестала
        /// ехать рука».
        /// </summary>
        [Test]
        public void Solve3_WellConditionedMatrix_Solves()
        {
            var a = new double[,] { { 0.01, 0, 0 }, { 0, 0.02, 0 }, { 0, 0, 0.05 } };
            var b = new double[] { 0.01, 0.02, 0.05 };

            var r = Solve3Caller()(a, b);
            Assert.IsTrue(r.Item1, "матрица с определителем 1e-5 обязана решаться — она не вырождена");
            Assert.AreEqual(1.0, r.Item2[0], 1e-6);
            Assert.AreEqual(1.0, r.Item2[1], 1e-6);
            Assert.AreEqual(1.0, r.Item2[2], 1e-6);
        }

        // ---------------------------------------------------------------- 6. КОНСТРУКТОР

        /// <summary>
        /// БЕЗ СЦЕНЫ КЛАСС НЕ ГОТОВ, НО НЕ ПАДАЕТ. `Init(null)` — законный вызов (робот не выбран),
        /// и `Step` обязан вернуть исходную позу, а не пустоту: иначе планировщик получит null.
        /// </summary>
        [Test]
        public void WithoutValidator_StepReturnsSamePose()
        {
            var control = new PostureControl();
            control.Init(null, null);

            Assert.IsFalse(control.Ready, "без валидатора постура не готова");
            var q = new double[] { 0, 0, 0, 0, 0, 0 };
            double[] result = control.Step(q, new Vector3(1f, 0f, 0f), 1f / 60f);

            Assert.IsNotNull(result, "Шаг обязан вернуть массив, а не null");
            Assert.AreEqual(q, result, "без готового валидатора поза обязана остаться прежней");
        }

        /// <summary>
        /// ВЫХОД ЗА ГРАНИЦЫ ШАГА ОГРАНИЧЕН. Это ключевое обещание постуры: «шаг по суставам
        /// ограничен скоростями». Без сцены полноценно не проверить, но контракт «БЕЗ валидатора
        /// шаг не делается вовсе» проверяется и он важен: он не даёт молча крутить робота.
        /// </summary>
        [Test]
        public void WithoutValidator_PoseIsNotModifiedInPlace()
        {
            var control = new PostureControl();
            control.Init(null, null);
            var q = new double[] { 10, 20, 30, 40, 50, 60 };
            var copy = (double[])q.Clone();

            control.Step(q, Vector3.zero, 1f / 60f);

            Assert.AreEqual(copy, q,
                "Step не должен менять позу на месте: вызывающий передаёт её по ссылке и не ждёт мутации");
        }
    }
}
