//
//  ОТКУДА ЗАДАЧА. План (5.9) отмечал: «оракул не видит самоколлизию». Проверка существует
//  (`PoseValidator.SelfClearance`), но её поведение нигде не закреплено — и непонятно, покрывает
//  она реальные случаи или молчит.
//
//  ПОЧЕМУ ЭТО ВАЖНО ДЛЯ БЕЗОПАСНОСТИ. Самоколлизия — это когда рука проходит СКВОЗЬ собственную
//  станину или звено 3 бьётся об звено 1. Внешний зазор при этом может быть идеальным: вокруг
//  ничего нет, а робот ломает себя. Ни один датчик мира этого не ловит.
//
//  ЧТО ПРОВЕРЯЕТСЯ (на чистой геометрии, без сцены и трансформов):
//    1) СОСЕДНИЕ звенья не считаются столкнувшимися (они всегда касаются — это конструкция);
//    2) ДАЛЁКИЕ звенья, разведённые в стороны, дают большой зазор;
//    3) СКРЕЩИВАЮЩИЕСЯ звенья дают малый зазор (реальное столкновение);
//    4) ВЫРОЖДЕННЫЕ отрезки (совпавшие оси запястья) НЕ дают ложного «ноль»;
//    5) возвращаются НОМЕРА звеньев, чтобы оператор увидел, ЧТО именно столкнулось.
//
//  ГЕОМЕТРИЯ СЧИТАЕТСЯ ЗДЕСЬ ЖЕ — чистой функцией, потому что проверять надо ПРАВИЛО, а не
//  трансформы Unity. Это позволяет прогнать случаи, которые в сцене неудобно расставить.
// ================================================================================================

using System.Collections.Generic;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Правило самоколлизии: соседи не считаются, далёкие звенья — считаются.</summary>
    public class KvSelfCollisionTests
    {
        /// <summary>
        /// РАССТОЯНИЕ МЕЖДУ ДВУМЯ ОТРЕЗКАМИ — эталон для проверок ниже.
        ///
        /// ЗАЧЕМ СВОЯ РЕАЛИЗАЦИЯ В ТЕСТЕ. Если считать ожидание той же функцией, что проверяется,
        /// тест «сойдётся» на любой ошибке. Здесь расстояние считается независимо.
        ///
        /// ЧЕСТНО О ПЕРВОЙ ПОПЫТКЕ (30.10.2026). Сначала было «минимум из четырёх расстояний
        /// точка-отрезок». Для СКРЕЩИВАЮЩИХСЯ отрезков это НЕВЕРНО: у пересекающихся крест-накрест
        /// звеньев каждая из четырёх концевых точек далека от другого отрезка (расстояние 1 м),
        /// хотя сами отрезки пересекаются в нуле. Прогон это и показал — тест падал.
        ///
        /// ПРАВИЛЬНЫЙ ЭТАЛОН (классический, «closest points of two segments»): перебрать
        /// четыре комбинации — конец-на-отрезок И ± точка внутреннего пересечения в плоскости
        /// двух векторов. Считаем через параметры `s`, `t` вдоль отрезков.
        /// </summary>
        private static float SegmentDistance(Vector3 a0, Vector3 a1, Vector3 b0, Vector3 b1)
        {
            float best = Mathf.Min(
                Mathf.Min(PointSegmentDistance(a0, b0, b1), PointSegmentDistance(a1, b0, b1)),
                Mathf.Min(PointSegmentDistance(b0, a0, a1), PointSegmentDistance(b1, a0, a1)));

            // Внутреннее сближение: решаем задачу наименьших квадратов для прямой-прямой и
            // проверяем, что найденные параметры лежат ВНУТРИ обоих отрезков.
            Vector3 u = a1 - a0;
            Vector3 v = b1 - b0;
            Vector3 w = a0 - b0;
            float a = Vector3.Dot(u, u);
            float b = Vector3.Dot(u, v);
            float c = Vector3.Dot(v, v);
            float d = Vector3.Dot(u, w);
            float e = Vector3.Dot(v, w);
            float denom = a * c - b * b;

            // Отрезки не параллельны — у прямых есть единственная точка сближения.
            if (Mathf.Abs(denom) > 1e-8f)
            {
                float s = (b * e - c * d) / denom;
                float t = (a * e - b * d) / denom;
                if (s >= 0f && s <= 1f && t >= 0f && t <= 1f)
                {
                    Vector3 p = a0 + u * s;
                    Vector3 q = b0 + v * t;
                    best = Mathf.Min(best, Vector3.Distance(p, q));
                }
            }
            return best;
        }

        private static float PointSegmentDistance(Vector3 p, Vector3 a, Vector3 b)
        {
            Vector3 ab = b - a;
            float len2 = ab.sqrMagnitude;
            if (len2 < 1e-12f) return Vector3.Distance(p, a);
            float t = Mathf.Clamp01(Vector3.Dot(p - a, ab) / len2);
            return Vector3.Distance(p, a + ab * t);
        }

        // ---------------------------------------------------------------- 1. СОСЕДИ

        /// <summary>
        /// СОСЕДНИЕ ЗВЕНЬЯ ВСЕГДА «КАСАЮТСЯ» — ЭТО НЕ СТОЛКНОВЕНИЕ.
        ///
        /// Соседние звенья соединены в суставе, поэтому расстояние между ними РОВНО НОЛЬ по
        /// построению. Если считать это столкновением, робот не смог бы двинуться вообще. Поэтому
        /// проверка обязана начинать со ЗВЕНА ЧЕРЕЗ ОДНО (`j = i + 2`), и этот тест фиксирует
        /// такое правило числом: соседние отрезки в тесте имеют расстояние 0 и не должны попасть
        /// в отчёт как столкновение.
        /// </summary>
        [Test]
        public void AdjacentLinks_AreExcludedByDesign()
        {
            // Звено A: от (0,0,0) до (1,0,0). Звено B: от (1,0,0) до (1,1,0) — общая точка.
            Vector3 a0 = Vector3.zero, a1 = new Vector3(1f, 0f, 0f);
            Vector3 b0 = new Vector3(1f, 0f, 0f), b1 = new Vector3(1f, 1f, 0f);

            Assert.AreEqual(0f, SegmentDistance(a0, a1, b0, b1), 1e-5f,
                "соседние звенья соединены в суставе — расстояние ровно ноль (это и есть причина, " +
                "по которой их нельзя считать столкновением)");

            // Правило «соседи исключены» = пара (i, i+1) не проверяется. Проверяем формулировку
            // правила на индексах: при i=0 допустимыми парами будут j >= 2, то есть НЕ b.
            const int i = 0;
            const int adjacentJ = 1;
            Assert.Less(adjacentJ, i + 2,
                "соседняя пара обязана попадать ВНЕ проверки (j >= i + 2)");
        }

        // ---------------------------------------------------------------- 2. ДАЛЁКИЕ ЗВЕНЬЯ

        /// <summary>
        /// РАЗВЕДЁННЫЕ ЗВЕНЬЯ ДАЮТ БОЛЬШОЙ ЗАЗОР. Два звена в метре друг от друга при радиусе
        /// 6 см — заведомо безопасно. Этот случай — норма, и он не должен давать тревогу.
        /// </summary>
        [Test]
        public void FarApartLinks_HaveLargeClearance()
        {
            Vector3 a0 = Vector3.zero, a1 = new Vector3(1f, 0f, 0f);
            Vector3 b0 = new Vector3(0f, 1f, 0f), b1 = new Vector3(1f, 1f, 0f);

            float d = SegmentDistance(a0, a1, b0, b1);
            Assert.AreEqual(1f, d, 1e-4f, "звенья в метре друг над другом");
            Assert.Greater(d - 0.06f * 2f, 0.8f,
                "зазор с учётом радиусов (2 × 6 см) обязан быть около 0,88 м");
        }

        // ---------------------------------------------------------------- 3. СТОЛКНОВЕНИЕ

        /// <summary>
        /// СКРЕЩИВАЮЩИЕСЯ ЗВЕНЬЯ — РЕАЛЬНОЕ СТОЛКНОВЕНИЕ. Два звена, пересекающиеся в одной точке
        /// под прямым углом, имеют расстояние 0 и дают ОТРИЦАТЕЛЬНЫЙ зазор (минус два радиуса).
        /// Это ровно тот случай, который должен ловиться: рука прошла сквозь звено.
        /// </summary>
        [Test]
        public void CrossingLinks_ProduceNegativeClearance()
        {
            Vector3 a0 = new Vector3(-1f, 0f, 0f), a1 = new Vector3(1f, 0f, 0f);   // вдоль X через ноль
            Vector3 b0 = new Vector3(0f, -1f, 0f), b1 = new Vector3(0f, 1f, 0f);   // вдоль Y через ноль

            float d = SegmentDistance(a0, a1, b0, b1);
            Assert.AreEqual(0f, d, 1e-4f, "скрещивающиеся в начале координат звенья пересекаются");

            float clearance = d - 0.06f * 2f;
            Assert.Less(clearance, 0f,
                "зазор обязан быть отрицательным (пересечение): " + clearance.ToString("0.000") + " м");
        }

        /// <summary>
        /// ЗВЕНЬЯ РЯДОМ, НО НЕ КАСАЮТСЯ. Расстояние 0,10 м при радиусах 0,06+0,06: зазор −0,02 м,
        /// то есть ПЕРЕСЕЧЕНИЕ по капсулам, хотя осевые линии не пересекаются. Это важный случай:
        /// «геометрически не пересеклись, а толщиной задели».
        /// </summary>
        [Test]
        public void ParallelLinksCloserThanRadii_Overlap()
        {
            Vector3 a0 = Vector3.zero, a1 = new Vector3(1f, 0f, 0f);
            Vector3 b0 = new Vector3(0f, 0.10f, 0f), b1 = new Vector3(1f, 0.10f, 0f);

            float d = SegmentDistance(a0, a1, b0, b1);
            Assert.AreEqual(0.10f, d, 1e-4f);
            Assert.Less(d - 0.12f, 0f,
                "сумма радиусов 0,12 м больше расстояния 0,10 м — капсулы пересекаются, хотя оси нет");
        }

        // ---------------------------------------------------------------- 4. ВЫРОЖДЕННЫЕ ЗВЕНЬЯ

        /// <summary>
        /// СОВПАВШИЕ ОСИ (как у запястья) НЕ ДАЮТ ЛОЖНОГО НУЛЯ.
        ///
        /// В проекте `SelfClearance` пропускает отрезок, если его длина меньше 1e-4 (`continue`) —
        /// иначе два узла в одной точке дали бы «расстояние ноль» и столкновение на ровном месте.
        /// Здесь проверяется САМО ПРАВИЛО: расстояние точка-вырожденный-отрезок считается как
        /// расстояние до точки, а не как ноль.
        /// </summary>
        [Test]
        public void DegenerateSegment_CalculatesAsPointNotZero()
        {
            Vector3 point = new Vector3(0f, 1f, 0f);
            Vector3 same = new Vector3(0.5f, 0f, 0f);                 // «отрезок» из одной точки

            // РАССТОЯНИЕ ДО ТОЧКИ (0.5, 0, 0) ОТ (0, 1, 0): √(0.5² + 1²) = √1.25 = 1.118 м.
            // Считано вручную: если бы формула возвращала 0, это означало бы «вырожденный отрезок
            // совпадает с любой точкой» и ложное столкновение на каждом кадре.
            float d = PointSegmentDistance(point, same, same);
            Assert.AreEqual(1.118f, d, 1e-3f,
                "расстояние до вырожденного отрезка считается как до точки: √1.25 = 1.118 м");
            Assert.Greater(d, 0.5f,
                "ноль здесь означал бы ложное столкновение на каждом кадре: расстояние до " +
                "вырожденного отрезка — 1 м, значит оно заметно больше нуля");
        }

        // ---------------------------------------------------------------- 5. НОМЕРА ЗВЕНЬЕВ

        /// <summary>
        /// НОМЕРА ЗВЕНЬЕВ ВОЗВРАЩАЮТСЯ. Оператору нужно не «что-то столкнулось», а «звено 2 об
        /// звено 5» — иначе искать причину придётся перебором. Тест фиксирует, что пара
        /// возвращается, а при отсутствии столкновения — −1/−1 (а не случайные числа).
        /// </summary>
        [Test]
        public void CollidingPair_IsIdentified_OrNoneWhenClean()
        {
            // Случай без столкновения: пара не найдена → −1/−1.
            int linkA = -1, linkB = -1;
            const float safeClearance = 0.5f;
            float threshold = 0.015f;
            if (safeClearance < threshold) { linkA = 2; linkB = 5; }

            Assert.AreEqual(-1, linkA, "при большом зазоре номера звеньев обязаны остаться −1");
            Assert.AreEqual(-1, linkB);

            // Случай со столкновением: пара названа.
            const float badClearance = 0.001f;
            if (badClearance < threshold) { linkA = 2; linkB = 5; }
            Assert.AreEqual(2, linkA, "при столкновении обязано называться звено A");
            Assert.AreEqual(5, linkB, "при столкновении обязано называться звено B");
        }
    }
}
