// ================================================================================================
//  KvXrTrackingLossTests.cs — EditMode-тесты ОТКАЗОВ ОТСЛЕЖИВАНИЯ (сессия S44).
//
//  ОТКУДА ЗАДАЧА. Потеря отслеживания — ШТАТНЫЙ отказ в шлеме, а не исключение: оператор опустил
//  руку, вышел из зоны камер, прикрыл контроллер. Приложение обязано это пережить и СКРЫТЬ модель,
//  а не оставить её висеть в воздухе или приклеить к полу.
//
//  ЧТО УЖЕ СДЕЛАНО В ПРОЕКТЕ (проверено 30.10.2026): `KvXrControllerVisuals.IsPoseUsable` отбрасывает
//  позу по трём признакам, и все три взяты из ЖИВЫХ дефектов:
//    • нет признака `isTracked`;
//    • поза НУЛЕВАЯ — ловушка [F2]: «контроллер на полу» (нулевая поза означает «данных нет», а не
//      «контроллер в начале координат»);
//    • поза НЕВОЗМОЖНАЯ — дальше трёх метров от оператора в комнате не бывает.
//
//  ЧТО ЗАКРЕПЛЯЕТСЯ ЗДЕСЬ: эти правила не должны потеряться при правках. Отказ отслеживания —
//  самый частый раздражитель в шлеме: если модель «застревает» в воздухе, оператор видит, что мир
//  сломался, хотя всё в порядке.
//
//  ГРАНИЦА ЧЕСТНОСТИ: это правила ПОЗЫ, а не проверка самого железа. Реальную потерю отслеживания
//  воспроизводит шлем, а не тест.
// ================================================================================================

using KazistovVvXr;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Отказы отслеживания: модель скрывается, а не висит в воздухе.</summary>
    public class KvXrTrackingLossTests
    {
        // ---------------------------------------------------------------- 1. НЕТ ОТСЛЕЖИВАНИЯ

        /// <summary>
        /// НЕТ ПРИЗНАКА `isTracked` — ПОЗА НЕ ГОДИТСЯ, каким бы ни было положение.
        ///
        /// ПОЧЕМУ ЭТО ВАЖНЕЕ ВСЕГО: без этого признака приложение верит «последнему известному»
        /// положению, и модель контроллера остаётся висеть в воздухе там, где рука была секунду
        /// назад. Оператор видит «призрака» и считает, что сломался шлем.
        /// </summary>
        [Test]
        public void NotTracked_IsNeverUsable()
        {
            var positions = new[]
            {
                Vector3.zero,
                new Vector3(0.2f, 1.2f, 0.4f),      // обычное положение руки
                new Vector3(2.5f, 1.0f, 0f),        // почти на пределе дальности
            };

            foreach (Vector3 position in positions)
            {
                Assert.IsFalse(KvXrControllerVisuals.IsPoseUsable(false, position),
                    "поза без признака отслеживания признана годной (позиция " + position +
                    ") — модель будет висеть в воздухе");
            }
        }

        // ---------------------------------------------------------------- 2. НУЛЕВАЯ ПОЗА

        /// <summary>
        /// НУЛЕВАЯ ПОЗА — НЕ ГОДИТСЯ (ловушка [F2]).
        ///
        /// ПОЧЕМУ ЭТО НЕ «КОНТРОЛЛЕР В НАЧАЛЕ КООРДИНАТ»: начало координат — это ПОЛ под ногами
        /// оператора. Нулевая поза в OpenXR означает «данных нет». Если её принять за настоящую,
        /// модель провалится сквозь пол — а это уже случалось ([F2] «контроллер на полу»).
        /// </summary>
        [Test]
        public void ZeroPosition_IsNotUsable()
        {
            Assert.IsFalse(KvXrControllerVisuals.IsPoseUsable(true, Vector3.zero),
                "нулевая поза принята за настоящую — модель провалится сквозь пол ([F2])");

            // Близкие к нулю значения тоже отбрасываются: они означают дрожание сенсора, а не
            // реальное положение руки.
            Assert.IsFalse(KvXrControllerVisuals.IsPoseUsable(true, new Vector3(0.005f, 0f, 0f)),
                "поза в 5 мм от начала координат принята за настоящую — это дрожание, а не рука");
        }

        // ---------------------------------------------------------------- 3. НЕВОЗМОЖНАЯ ПОЗА

        /// <summary>
        /// ПОЗА ДАЛЬШЕ ТРЁХ МЕТРОВ — НЕ ГОДИТСЯ. В комнате оператора рука не может быть дальше трёх
        /// метров от центра. Такая поза означает ошибку рантайма или переход в другую систему
        /// координат; принять её — значит утащить модель за пределы комнаты.
        /// </summary>
        [Test]
        public void ImpossibleDistance_IsNotUsable()
        {
            Assert.IsFalse(KvXrControllerVisuals.IsPoseUsable(true, new Vector3(0f, 0f, 5f)),
                "поза в 5 метрах признана годной — рука не может быть так далеко");
            Assert.IsFalse(KvXrControllerVisuals.IsPoseUsable(true, new Vector3(10f, 0f, 0f)),
                "поза в 10 метрах признана годной");
        }

        // ---------------------------------------------------------------- 4. НОРМА

        /// <summary>
        /// ОБЫЧНАЯ ПОЗА РУКИ — ГОДИТСЯ. Обратная ошибка («отбрасываем всё») тоже дефект: тогда
        /// модели контроллеров не появятся никогда, и оператор останется без указателя.
        /// </summary>
        [Test]
        public void NormalHandPosition_IsUsable()
        {
            // Типичные положения руки в комнате оператора.
            var good = new[]
            {
                new Vector3(0.25f, 1.2f, 0.35f),     // рука перед собой
                new Vector3(-0.4f, 1.0f, 0.2f),      // рука сбоку
                new Vector3(0f, 1.6f, 0.5f),         // поднятая рука
                new Vector3(0.3f, 0.9f, 0.1f),       // опущенная рука
            };

            foreach (Vector3 position in good)
            {
                Assert.IsTrue(KvXrControllerVisuals.IsPoseUsable(true, position),
                    "обычное положение руки (" + position + ") признано негодным — модели " +
                    "контроллеров не появятся");
            }
        }

        /// <summary>
        /// ГРАНИЦЫ ДИАПАЗОНА. Проверяются значения РЯДОМ с порогами: 1 см (нижний) и 3 м (верхний).
        /// Слишком строгие пороги лишат оператора модели, слишком мягкие — пропустят мусор.
        ///
        /// Допуск в тесте — 2 см: округление float даёт небольшую разницу, и «ровно на пороге» —
        /// плохая проверка в обе стороны.
        /// </summary>
        [Test]
        public void ThresholdsAreReasonable()
        {
            // Чуть выше нижнего порога (1 см) — должно проходить.
            Assert.IsTrue(KvXrControllerVisuals.IsPoseUsable(true, new Vector3(0.03f, 0f, 0f)),
                "поза в 3 см отброшена — порог нижней границы слишком высокий");

            // Чуть ниже верхнего порога (3 м) — должно проходить.
            Assert.IsTrue(KvXrControllerVisuals.IsPoseUsable(true, new Vector3(0f, 0f, 2.9f)),
                "поза в 2,9 м отброшена — порог верхней границы слишком низкий");

            // Намного выше верхнего порога — отбрасывается.
            Assert.IsFalse(KvXrControllerVisuals.IsPoseUsable(true, new Vector3(0f, 0f, 3.5f)),
                "поза в 3,5 м принята — порог верхней границы слишком мягкий");
        }

        // ---------------------------------------------------------------- 5. ГРАНИЧНЫЕ ЗНАЧЕНИЯ

        /// <summary>
        /// NaN И БЕСКОНЕЧНОСТЬ ОТБРАСЫВАЮТСЯ. Позиция с NaN появляется от деления на ноль внутри
        /// рантайма; если её принять, модель исчезнет из мира навсегда (Unity не рисует объекты с
        /// NaN-координатами), и найти причину будет крайне трудно.
        /// </summary>
        [Test]
        public void NaNPosition_IsRejected()
        {
            var nan = new Vector3(float.NaN, 1f, 0.3f);
            var infinity = new Vector3(float.PositiveInfinity, 1f, 0.3f);

            // Сравнение `distance > 3f` для NaN даёт false, и `distance < 0.01f` тоже false —
            // то есть NaN мог бы ПРОЙТИ проверку. Тест это и выясняет.
            bool nanUsable = KvXrControllerVisuals.IsPoseUsable(true, nan);
            bool infUsable = KvXrControllerVisuals.IsPoseUsable(true, infinity);

            Assert.IsFalse(infUsable,
                "позиция с бесконечностью признана годной — модель окажется вне мира");

            if (nanUsable)
                Assert.Fail("позиция с NaN признана ГОДНОЙ: `Vector3.magnitude` для NaN даёт NaN, " +
                            "и оба сравнения с порогами дают false — значит проверка не отсекает NaN. " +
                            "Модель с такой позицией НЕ ОТРИСОВЫВАЕТСЯ Unity, и найти причину " +
                            "крайне трудно");
        }
    }
}
