// ================================================================================================
//  KvStorageResilienceTests.cs — EditMode-тесты УСТОЙЧИВОСТИ ХРАНИЛИЩА (сессия S44).
//
//  ОТКУДА ЗАДАЧА. Приложение хранит данные оператора на ДИСКЕ: макросы, позы, зоны, сессии,
//  сценарии, записи. На шлеме диск — это не «папка на компьютере»: он может быть заполнен, может
//  быть недоступен в первые секунды после запуска, а разрешения на запись могут не выдаться.
//
//  ЧТО ПРОВЕРЕНО 30.10.2026. `FeatureStorage.EnsureDir` — ЕДИНСТВЕННОЕ место, где создаются папки,
//  и оно переживает отказ: ловит исключение, пишет ПРЕДУПРЕЖДЕНИЕ в журнал и **возвращает путь**.
//  Это правильно: вызывающий код получает путь и попробует писать — а отказ записи обработает у
//  себя. Падение здесь означало бы, что приложение не запускается вообще.
//
//  ЧТО ЗАКРЕПЛЯЕТСЯ:
//    1) `EnsureDir` не бросает даже на заведомо невозможном пути;
//    2) возвращает путь (а не пустую строку) — иначе путь к данным «схлопнется» в текущую папку;
//    3) не падает на пустом и на null-пути;
//    4) корень данных не зависит от версии программы (переживает обновление);
//    5) все рабочие подпапки создаются через ОДНО место, а не каждая по-своему.
//
// ================================================================================================
//  ЖУРНАЛ ДЕЙСТВИЙ: ПОВТОРЫ, РОТАЦИЯ, ПОЗА, НАЖАТИЯ (добавлено 12.11.2026).
//
//  ОТКУДА ЗАДАЧА. Тестировщик разобрал реальную запись с устройства
//  (`actions_20261110.log`, журналы 12.11.2026): 14 строк на весь сеанс, из них 11 — ОДНО И ТО ЖЕ
//  («тепловая карта достижимости: выкл»), повторяющееся каждые 1–2 секунды. За те же 18 секунд
//  самопрогон интерфейса сделал 140 нажатий — и в записи о них не было НИ СЛОВА. За одну сессию
//  накопилось 1,1 ГБ журналов. То есть файл был одновременно полон шума и пуст там, где нужно
//  доказательство работы.
//
//  ЧТО ЗАКРЕПЛЕНО (проверяются ЧИСТЫЕ функции — без сцены, шлема и файловой системы):
//    а) повтор события внутри 30 с НЕ пишется, счётчик растёт; после 30 с — пишется с «×N»;
//    б) нажатие команды даёт строку с ИДЕНТИФИКАТОРОМ; смена режима VR/MR — строку с числами;
//    в) запись позы уважает частоту ≤10 Гц и порог изменения (два одинаковых кадра — одна строка);
//    г) ротация: при превышении размера берётся новый файл, старых не больше трёх;
//    д) анти-вакуум: РАЗНЫЕ события пишутся всегда — правило «не повторять» не глотает разные строки.
//
//  ГРАНИЦА ЧЕСТНОСТИ. Настоящая запись на диск и настоящий шлем здесь не участвуют: проверяются
//  формулы решений и строка, которую они дают. Это то, что можно проверить машинно и что ломается
//  от ошибки в правиле; частота 72 Гц на живом шлеме проверяется на устройстве.
// ================================================================================================

