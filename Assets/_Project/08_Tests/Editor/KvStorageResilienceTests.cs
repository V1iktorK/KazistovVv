        /// <summary>
        /// (а) ПОВТОР ВНУТРИ 30 СЕКУНД НЕ ПИШЕТСЯ, А СЧЁТЧИК РАСТЁТ; ПОСЛЕ 30 С — ПИШЕТСЯ С «×N».
        ///
        /// ЧТО БЫЛО. Одно и то же событие («тепловая карта достижимости: выкл») ложилось в файл
        /// каждые 1–2 секунды: 11 одинаковых строк из 14 за сеанс. За сессию так набралось 1,1 ГБ.
        ///
        /// ЧЕМ ПЛОХО. Полезные строки тонули в шуме, а файл нельзя было ни открыть, ни переслать.
        ///
        /// ЧТО СТАЛО. Решение «писать или нет» принимает чистая функция `ShouldWrite`: внутри окна —
        /// нет (только счётчик), после окна — да. Счётчик подавленных уходит в строку хвостом «×N»,
        /// поэтому по журналу видно не только «случилось», но и «сколько раз долбило».
        ///
        /// ПОЧЕМУ ЧАСЫ ПОДСТАВЛЯЮТСЯ. Ждать настоящие 30 секунд в тесте нельзя — прогон замедлился
        /// бы на десятки секунд. Часы — параметр функции, а не `Time.realtimeSinceStartup` внутри
        /// неё, именно ради этой проверки.
        /// </summary>
        [Test]
        public void RepeatWithinWindowIsSuppressedAndCounted()
        {
            const float window = KvActionLog.RepeatWindowSeconds;
            Assert.AreEqual(30f, window, "окно отсечения повторов изменилось — числа в отчёте разъедутся");

            // ПЕРВАЯ ЗАПИСЬ: истории нет — писать всегда.
            Assert.IsTrue(KvActionLog.ShouldWrite(double.NaN, 100.0, window, true),
                "первое событие не записалось: журнал остался бы пустым при любом правиле отсечения");

            // ПОВТОР ЧЕРЕЗ 1 С: внутри окна — НЕ писать (это и есть лечение дефекта).
            Assert.IsFalse(KvActionLog.ShouldWrite(100.0, 101.0, window, true),
                "повтор через 1 с записан: ровно этот дефект дал 11 одинаковых строк из 14");
            Assert.IsFalse(KvActionLog.ShouldWrite(100.0, 129.9, window, true),
                "повтор за мгновение до конца окна записан — окно отсечения короче объявленного");

            // ГРАНИЦА: ровно 30 с — уже можно (окно истекло, состояние считается новым).
            Assert.IsTrue(KvActionLog.ShouldWrite(100.0, 130.0, window, true),
                "повтор ровно через 30 с не записан: событие потерялось бы навсегда, а не «раз в 30 с»");

            // СЧЁТЧИК: три подавленных повтора дают хвост «×4» (первый + три подавленных).
            string line = KvActionLog.ComposeText("тепловая карта достижимости: выкл", 3);
            StringAssert.EndsWith("… ×4", line,
                "число повторов не приписано к строке — по записи нельзя отличить «было раз» от " +
                "«долбило каждую секунду»");
            StringAssert.StartsWith("тепловая карта достижимости: выкл", line,
                "хвост счётчика испортил сам текст события");

            // БЕЗ ПОДАВЛЕННЫХ: строка выглядит как раньше (старый разбор журнала не ломается).
            Assert.AreEqual("тепловая карта достижимости: выкл",
                KvActionLog.ComposeText("тепловая карта достижимости: выкл", 0),
                "при нуле подавленных к строке приписан хвост «×N» — старая форма записи испорчена");

            // ОТСЕЧЕНИЕ ВЫКЛЮЧЕНО: пишем всегда (это выключатель для разбора, а не второй режим).
            Assert.IsTrue(KvActionLog.ShouldWrite(100.0, 100.1, window, false),
                "при выключенном отсечении повтор не записался — выключатель не работает");
        }

        /// <summary>
        /// (б1) НАЖАТИЕ КОМАНДЫ ДАЁТ СТРОКУ С ИДЕНТИФИКАТОРОМ.
        ///
        /// ЧТО БЫЛО. Нажатие жило только в консоли Unity: 140 нажатий самопрогона не оставили в
        /// файле записи ни строки. Тестировщик не мог подтвердить, что оператор вообще нажимал.
        ///
        /// ЧЕМ ПЛОХО. Запись без нажатий — это отчёт без событий: по ней нельзя разобрать, какая
        /// кнопка привела к какому поведению.
        ///
        /// ЧТО СТАЛО. Строка строится чистой функцией `FormatCommandLine` и ОБЯЗАНА содержать
        /// идентификатор команды: по нему строка связывается с реестром.
        /// </summary>
        [Test]
        public void CommandPressLineCarriesIdentifier()
        {
            string line = KvActionLog.FormatCommandLine("view.heatmap",
                "Тепловая карта достижимости", "выполнена");

            StringAssert.Contains("view.heatmap", line,
                "в строке нажатия нет ИДЕНТИФИКАТОРА команды — строку нельзя связать с реестром");
            StringAssert.Contains("Тепловая карта достижимости", line,
                "в строке нажатия нет заголовка команды — оператор не узнает, о какой кнопке речь");
            StringAssert.Contains("выполнена", line, "в строке нажатия нет результата");

            // ОТКАЗ ТОЖЕ ПИШЕТСЯ — и с причиной: «нажал, ничего не произошло» без причины
            // бесполезно для разбора.
            string refused = KvActionLog.FormatCommandLine("robot.model.kuka",
                "Робот: KUKA", "недоступна: в разработке");
            StringAssert.Contains("robot.model.kuka", refused, "отказ команды потерял её идентификатор");
            StringAssert.Contains("недоступна", refused, "отказ команды не назвал причину");

            // АНТИ-ВАКУУМ: разные команды дают РАЗНЫЕ строки (иначе формат склеил бы всё в одно).
            Assert.AreNotEqual(line,
                KvActionLog.FormatCommandLine("view.clearance", "Тепловая карта зазоров", "выполнена"),
                "две разные команды дают одинаковую строку — по записи их не различить");
        }

        /// <summary>
        /// (б2) СМЕНА РЕЖИМА VR/MR ДАЁТ СТРОКУ С ЧИСЛАМИ.
        ///
        /// ЧТО БЫЛО. Режим печатался только в консоль Unity. Разбор записи с устройства не мог
        /// ответить, в каком режиме работал оператор, — а «робот на полу» в VR и «робот на
        /// реальном столе» в MR это две разные картины одного и того же жеста.
        ///
        /// ЧЕМ ПЛОХО. Половина остальных строк записи без режима читается неверно.
        ///
        /// ЧТО СТАЛО. Строка смены несёт: откуда → куда, что доступно (пропускание/якоря/камера)
        /// и масштаб мира. Масштаб — условие работы MR (замер 1:1), а не оформление.
        /// </summary>
        [Test]
        public void ModeChangeLineCarriesNumbers()
        {
            string line = KvActionLog.FormatModeLine("VR", "MR", true, true, true, 1.0f);

            StringAssert.Contains("VR", line, "в строке смены режима нет прежнего режима");
            StringAssert.Contains("MR", line, "в строке смены режима нет нового режима");
            StringAssert.Contains("1.000", line,
                "в строке смены режима нет масштаба мира — по ней нельзя сверить замер 1:1");
            StringAssert.Contains("пропускание", line,
                "в строке смены режима нет доступности сквозного вида");

            // ЧИСЛА — ЧЕРЕЗ ТОЧКУ, а не через запятую: в русской локали «0,500» спутается
            // с разделителем списка при разборе журнала скриптами.
            string scaled = KvActionLog.FormatModeLine("VR", "MR", true, true, true, 0.5f);
            StringAssert.Contains("0.500", scaled,
                "масштаб напечатан не через точку — скрипт разбора примет его за разделитель списка");
            StringAssert.DoesNotContain("0,500", scaled,
                "масштаб напечатан через запятую — строка не разбирается скриптом");

            // ОТСУТСТВИЕ ВОЗМОЖНОСТИ ВИДНО: иначе «VR вместо MR» выглядит как дефект приложения.
            string vr = KvActionLog.FormatModeLine("MR", "VR", false, false, false, 1.0f);
            StringAssert.Contains("НЕТ", vr,
                "недоступность сквозного вида не названа — причина выбора VR осталась невидимой");
        }

        /// <summary>
        /// (в) ЗАПИСЬ ПОЗЫ УВАЖАЕТ ЧАСТОТУ ≤10 Гц И ПОРОГ ИЗМЕНЕНИЯ: два одинаковых кадра — ОДНА строка.
        ///
        /// ЧТО БЫЛО. Позы в записи не было вовсе, и наладчику нечем было ответить «куда смотрел
        /// оператор, когда робот поехал не туда».
        ///
        /// ЧЕМ ПЛОХО БЫЛО БЫ ПИСАТЬ КАЖДЫЙ КАДР. `Update` подачи взгляда идёт на 72 Гц: наивная
        /// запись — это 72 строки в секунду, то есть тот же 1,1 ГБ, от которого только что вылечили
        /// повторы. Лекарство не имеет права быть новой болезнью.
        ///
        /// ЧТО СТАЛО. `PoseDue` требует ОБА условия: прошло не меньше 1/10 с И поза заметно
        /// изменилась (5 см или 5°). Проверяются все четыре ветки, включая «не изменилась».
        /// </summary>
        [Test]
        public void PoseLoggingRespectsRateAndThreshold()
        {
            const float minInterval = KvActionLog.PoseMinIntervalSeconds;
            Assert.AreEqual(0.1f, minInterval, 1e-5f,
                "минимальный интервал записи позы не 1/10 с — частота перестала быть «не более 10 Гц»");

            // ПЕРВАЯ ПОЗА ПИШЕТСЯ ВСЕГДА: иначе журнал молчал бы, пока оператор стоит неподвижно.
            Assert.IsTrue(KvActionLog.PoseDue(float.PositiveInfinity, float.PositiveInfinity,
                float.PositiveInfinity, false),
                "первая поза не записалась — записи не будет вообще, пока оператор не двинется");

            // ДВА ОДИНАКОВЫХ КАДРА → ОДНА СТРОКА (второй кадр не проходит порог изменения).
            Assert.IsFalse(KvActionLog.PoseDue(0.5f, 0.0f, 0.0f, true),
                "неизменившаяся поза записана второй раз — журнал снова превращается в поток кадров");

            // ТОЛЬКО ПОРОГ ЧАСТОТЫ: поза изменилась сильно, но слишком рано — НЕ писать.
            Assert.IsFalse(KvActionLog.PoseDue(0.01f, 5.0f, 90.0f, true),
                "поза записана чаще 10 Гц — запись обгоняет объявленную частоту");

            // ТОЛЬКО ПОРОГ ИЗМЕНЕНИЯ: время прошло, но поза та же — НЕ писать (это «стою на месте»).
            Assert.IsFalse(KvActionLog.PoseDue(10f, 0.001f, 0.001f, true),
                "одинаковая поза записана через 10 с — журнал заполняется «я всё ещё стою»");

            // СДВИГ ГОЛОВЫ БОЛЬШЕ 5 СМ — писать.
            Assert.IsTrue(KvActionLog.PoseDue(0.5f, 0.20f, 0.0f, true),
                "заметный сдвиг головы не записан — поза оператора осталась невидимой в журнале");

            // ПОВОРОТ ВЗГЛЯДА БОЛЬШЕ 5° — писать (даже если голова не сдвинулась).
            Assert.IsTrue(KvActionLog.PoseDue(0.5f, 0.0f, 30f, true),
                "заметный поворот взгляда не записан — «куда смотрел» не восстановить");

            // НЕЧИСЛО — это потеря трекинга, а не изменение (правило E-21): не пишем.
            Assert.IsFalse(KvActionLog.PoseDue(float.NaN, 1.0f, 1.0f, true),
                "поза с нечисловым временем записана — строка с «NaN» бесполезна для разбора");

            // ВИД СТРОКИ — ровно тот, что читает наладчик (числа с точкой и двумя знаками).
            string line = KvActionLog.FormatPoseLine(12.4f,
                new Vector3(0.12f, 1.60f, -0.30f), new Vector3(0f, -0.20f, 0.98f), 30f);
            Assert.AreEqual(
                "t=12.4 с · позиция (0.12; 1.60; -0.30) · взгляд (0.00; -0.20; 0.98) · FPS 30",
                line, "строка позы отличается от согласованного вида");

            // Кириллица в строке — настоящая, а не «╨┐╨╛╨╖╨╕╤Ж╨╕╤П»: запись обязана быть UTF-8.
            StringAssert.Contains("позиция", line,
                "кириллица в строке позы испорчена — файл записи не в UTF-8");
        }

        /// <summary>
        /// (г) РОТАЦИЯ ПО РАЗМЕРУ: при превышении создаётся новый файл, старых не больше трёх.
        ///
        /// ЧТО БЫЛО. Путь к файлу записи был ОДИН и тот же, файл только дописывался. За одну сессию
        /// так накопилось 1,1 ГБ — файл нельзя ни открыть на телефоне, ни переслать через adb.
        ///
        /// ЧЕМ ПЛОХО. Журнал, который невозможно прочитать, не выполняет свою единственную задачу —
        /// быть уликой. Плюс забивается общее хранилище телефона.
        ///
        /// ЧТО СТАЛО. После 5 МБ начинается следующая часть (`actions_&lt;дата&gt;_2.log`), а лишние
        /// части удаляются. Проверяются ЧИСТЫЕ функции: какая часть следующая и какие файлы убрать.
        ///
        /// ИСПРАВЛЕНО 12.11.2026 ПО ПАДЕНИЮ В UNITY. Первый прогон дал
        ///     «полная первая часть не переключила запись на вторую: Expected 2, But was 1».
        /// Причина была не в правиле, а в том, КАК оно было записано: `NextPart` принимал функцию
        /// «номер → ПУТЬ» и спрашивал размер у файловой системы. Тест подсовывал строку «занято»
        /// вместо пути; файла с таким именем нет → размер 0 → часть «свободна» → функция честно
        /// отвечала 1. Тест измерял не логику переключения, а умение обмануть `FileInfo`.
        /// ЧТО СТАЛО: `NextPart` принимает РАЗМЕРЫ (`Func&lt;int, long&gt;`), тест отдаёт числа
        /// напрямую, и проверяется именно правило «пиши в первую неполную часть». Плюс добавлена
        /// ветка «часть чуть меньше порога — ещё дописываем в неё»: без неё проверка была бы
        /// односторонней и «переключение» могло бы срабатывать слишком рано.
        /// </summary>
        [Test]
        public void RotationStartsNewFileAndKeepsAtMostThree()
        {
            Assert.AreEqual(5L * 1024L * 1024L, KvActionLog.RotateAfterBytes,
                "порог ротации изменился — числа в отчёте разъедутся");
            Assert.AreEqual(3, KvActionLog.MaxLogFiles, "предел числа файлов журнала изменился");

            // ИМЕНА ЧАСТЕЙ: первая без номера (как раньше), дальше — с номером.
            Assert.AreEqual("actions_20261112.log",
                KvActionLog.PartFileName("actions_20261112", 1),
                "имя первой части изменилось — старые журналы перестали бы находиться");
            Assert.AreEqual("actions_20261112_2.log",
                KvActionLog.PartFileName("actions_20261112", 2),
                "имя второй части не совпадает с согласованным видом");

            // ПУСТОЙ ДИСК: пишем в первую часть.
            var sizes = new System.Collections.Generic.Dictionary<int, long>();
            Assert.AreEqual(1, NextPartFrom(sizes),
                "при отсутствии файлов запись началась не с первой части");

            // ПЕРВАЯ ЧАСТЬ ПОЛНА — берётся вторая.
            sizes[1] = KvActionLog.RotateAfterBytes;
            sizes[2] = 0L;
            Assert.AreEqual(2, NextPartFrom(sizes), "полная первая часть не переключила запись на вторую");

            // ЧАСТЬ ЧУТЬ МЕНЬШЕ ПОРОГА — ещё ДОПИСЫВАЕМ в неё, а не начинаем новую: иначе части
            // нарезались бы почти пустыми и «5 МБ» превратилось бы в «5 МБ минус строка».
            sizes[1] = KvActionLog.RotateAfterBytes - 1;
            Assert.AreEqual(1, NextPartFrom(sizes),
                "часть меньше порога считается полной — файл переключался бы раньше времени");

            // ВСЕ ТРИ ПОЛНЫ — начинается четвёртая (потом лишние будут удалены).
            sizes[1] = KvActionLog.RotateAfterBytes;
            sizes[2] = KvActionLog.RotateAfterBytes;
            sizes[3] = KvActionLog.RotateAfterBytes;
            sizes[4] = 0L;
            Assert.AreEqual(4, NextPartFrom(sizes),
                "полные части не переключили запись на следующую — файл рос бы без предела");

            // ЧТО УДАЛИТЬ: остаётся не больше трёх, удаляются САМЫЕ СТАРЫЕ (с меньшим номером).
            var parts = new System.Collections.Generic.List<int> { 1, 2, 3, 4 };
            var remove = KvActionLog.FilesToDelete(parts, KvActionLog.MaxLogFiles);
            CollectionAssert.AreEqual(new[] { 1 }, remove,
                "удаляется не самый старый файл — оператор потерял бы свежую часть журнала");

            var many = new System.Collections.Generic.List<int> { 1, 2, 3, 4, 5, 6 };
            var removeMany = KvActionLog.FilesToDelete(many, KvActionLog.MaxLogFiles);
            CollectionAssert.AreEqual(new[] { 1, 2, 3 }, removeMany,
                "из шести частей удаляются не три самые старые — частей останется больше трёх");

            // ТРЁХ ФАЙЛОВ ДОСТАТОЧНО — НИЧЕГО НЕ УДАЛЯЕМ (анти-вакуум: правило не режет всегда).
            var three = new System.Collections.Generic.List<int> { 1, 2, 3 };
            CollectionAssert.IsEmpty(KvActionLog.FilesToDelete(three, KvActionLog.MaxLogFiles),
                "при трёх файлах что-то удаляется — журнал теряет части без причины");

            // РОТАЦИЯ ВЫКЛЮЧЕНА (порог 0): всегда первая часть, как до правки.
            Assert.AreEqual(1, KvActionLog.NextPart(p => 0L, 0),
                "при выключенной ротации запись ушла не в первую часть");

            // ГРАНИЦА ПОРОГА: ровно 5 МБ — уже полон (иначе файл перевалит объявленный предел).
            Assert.IsTrue(KvActionLog.IsFull(KvActionLog.RotateAfterBytes, KvActionLog.RotateAfterBytes),
                "файл ровно в 5 МБ считается неполным — предел размера не соблюдается");
            Assert.IsFalse(KvActionLog.IsFull(KvActionLog.RotateAfterBytes - 1, KvActionLog.RotateAfterBytes),
                "файл меньше порога считается полным — части нарезались бы слишком мелко");
        }

        /// <summary>
        /// Следующая часть по «таблице размеров» — БЕЗ ДИСКА.
        ///
        /// ЗДЕСЬ БЫЛА ОШИБКА ТЕСТА (найдена прогоном в Unity 12.11.2026), и она поучительна.
        /// Первая версия этой обвязки подсовывала вместо пути строку «занято», рассчитывая, что
        /// «непустой путь = занято». Но `NextPart` спрашивал РАЗМЕР у файловой системы: файла
        /// «занято» нет → размер 0 байт → часть считается свободной → функция честно возвращала 1.
        /// Тест падал с «полная первая часть не переключила запись на вторую», хотя правило было
        /// исправно. Это ровно та ловушка, которую проект называет P4-3: проверка измеряла
        /// способность теста обмануть `FileInfo`, а не логику выбора части.
        ///
        /// ЧТО СТАЛО. `NextPart` принимает РАЗМЕРЫ (`Func&lt;int, long&gt;`), а не пути. Обвязка
        /// отдаёт числа из таблицы напрямую: ни одного обращения к диску, и проверяется именно
        /// правило «пиши в первую неполную часть».
        ///
        /// ЧЕСТНО О ГРАНИЦЕ. «Спросить размер у настоящего файла» теперь живёт в отдельной тонкой
        /// обёртке `NextPartOnDisk`, и она этой проверкой не покрыта — её поведение (взять
        /// `FileInfo.Length`) слишком простое, чтобы стоить файловых операций в быстром прогоне.
        /// Сама же ротация целиком проверена на реальном диске отдельно, при разработке.
        /// </summary>
        private static int NextPartFrom(System.Collections.Generic.Dictionary<int, long> sizes)
        {
            return KvActionLog.NextPart(
                p =>
                {
                    long size;
                    return sizes.TryGetValue(p, out size) ? size : 0L;
                },
                KvActionLog.RotateAfterBytes);
        }

        /// <summary>
        /// ОСНОВА ИМЕНИ ЧАСТИ РАСПОЗНАЁТСЯ ПРАВИЛЬНО: `actions_20261112_2` → `actions_20261112`.
        ///
        /// ЗДЕСЬ БЫЛА НАСТОЯЩАЯ ОШИБКА, найденная прогоном этой проверки на настоящих именах.
        /// Первая версия резала имя по последнему подчёркиванию, если хвост цифровой. И:
        ///     StemOfPart("actions_20261112")  →  "actions"
        /// потому что ДАТА `20261112` — это тоже сплошные цифры! Основа теряла день, и ротация
        /// начинала искать файлы `actions.log`, `actions_2.log`, которых нет. Снаружи это выглядит
        /// как «правило «не больше 3 файлов» написано, но не работает» — то есть ровно тот класс
        /// дефекта, который проект ловит начиная с S44.
        ///
        /// ЧЕМ ПЛОХО. Лишние части не удалялись бы никогда: файл журнала рос бы без предела, как
        /// и до правки, а комментарий обещал обратное.
        ///
        /// ЧТО СТАЛО. Номер части — цифры после подчёркивания, но НЕ дата (`yyyyMMdd`, 8 цифр).
        /// Проверяются со всех трёх сторон, чтобы функция не «резала всегда» и не «не резала
        /// никогда»: дата, номер, слово.
        /// </summary>
        [Test]
        public void LogPartStemIsParsedWithoutLosingTheDate()
        {
            Assert.AreEqual(8, KvActionLog.DateFormatLength, "длина даты в имени журнала изменилась");

            // ДАТА — НЕ НОМЕР ЧАСТИ (это была настоящая ошибка, см. описание выше).
            Assert.AreEqual("actions_20261112", KvActionLog.StemOfPart("actions_20261112"),
                "дата в имени принята за номер части: основа стала «actions» — ротация не найдёт " +
                "свои файлы и лишние части не удалятся НИКОГДА");

            // НОМЕР ЧАСТИ — РЕЖЕТСЯ.
            Assert.AreEqual("actions_20261112", KvActionLog.StemOfPart("actions_20261112_2"),
                "из имени второй части не восстановлена основа — лишние части не удалятся никогда");

            Assert.AreEqual("actions_20261112", KvActionLog.StemOfPart("actions_20261112_17"),
                "многозначный номер части не отрезан");

            // СЛОВО — НЕ НОМЕР ЧАСТИ: имя не трогаем (анти-вакуум, иначе функция резала бы всегда).
            Assert.AreEqual("actions_20261112_ночь", KvActionLog.StemOfPart("actions_20261112_ночь"),
                "слово после подчёркивания принято за номер части — у чужого файла отрезан хвост");

            // Пустое имя не роняет (это приходит из `Path.GetFileNameWithoutExtension`).
            Assert.AreEqual("", KvActionLog.StemOfPart(null), "null вместо имени роняет разбор");
            Assert.AreEqual("", KvActionLog.StemOfPart(""), "пустое имя роняет разбор");
        }

        /// <summary>
        /// (д) АНТИ-ВАКУУМ: РАЗНЫЕ СОБЫТИЯ ПИШУТСЯ ВСЕГДА — правило «не повторять» не глотает
        /// разные строки.
        ///
        /// ЧТО БЫЛО. Правило отсечения повторов можно сделать слишком широким: «не писать ничего
        /// чаще раза в 30 секунд» отрезало бы и НАСТОЯЩИЕ разные события — и получился бы журнал,
        /// который зеленеет (файл маленький!) ровно на том дефекте, от которого его лечили.
        ///
        /// ЧЕМ ПЛОХО. Оператор нажал три разные кнопки, а в записи одна: разбор невозможен, при
        /// этом «размер журнала в норме» — то есть метрика врёт.
        ///
        /// ЧТО СТАЛО. Ключ события включает модуль, действие и значение. Разные значения дают
        /// разные ключи, значит пишутся все — независимо от окна времени.
        /// </summary>
        [Test]
        public void DifferentEventsAreNeverSwallowed()
        {
            const float window = KvActionLog.RepeatWindowSeconds;

            string heat = KvActionLog.ComposeKey("интерфейс", "команда", "view.heatmap");
            string clearance = KvActionLog.ComposeKey("интерфейс", "команда", "view.clearance");
            string mode = KvActionLog.ComposeKey("система", "режим", "VR → MR");

            // ТРИ РАЗНЫХ СОБЫТИЯ В ОДНУ СЕКУНДУ — ключи разные, значит ни одно не отсекается.
            Assert.AreNotEqual(heat, clearance,
                "две разные команды дают ОДИН ключ — правило «не повторять» съест вторую");
            Assert.AreNotEqual(heat, mode,
                "команда и смена режима дают один ключ — разные события склеились");
            Assert.AreNotEqual(clearance, mode,
                "две разные команды дают один ключ — разные события склеились");

            // ПРАВИЛО ДЕЙСТВУЕТ ТОЛЬКО НА СВОЁ СОБЫТИЕ: после записи `heat` в момент 100
            // событие `clearance` в момент 100.5 обязано пройти (это НЕ повтор, а другое событие).
            Assert.IsFalse(KvActionLog.ShouldWrite(100.0, 100.5, window, true),
                "подготовка сорвана: повтор того же события внутри окна не отсекается");
            Assert.IsTrue(KvActionLog.ShouldWrite(double.NaN, 100.5, window, true),
                "новое (ещё не виденное) событие не записалось внутри окна — анти-вакуум нарушен");

            // ЧИСЛА ВНУТРИ ЗНАЧЕНИЯ НЕ ДЕЛАЮТ СОБЫТИЕ НОВЫМ: «зазор 0,31 м» и «зазор 0,29 м» —
            // это одно и то же событие, иначе отсечение не сработало бы там, где нужно.
            Assert.AreEqual(
                KvActionLog.ComposeKey("робот", "зазор", "0.31 м"),
                KvActionLog.ComposeKey("робот", "зазор", "0.29 м"),
                "два замера одного и того же события дали разные ключи — повторы не отсекутся никогда");

            // НО ТЕКСТ С РАЗНЫМ СМЫСЛОМ ОСТАЁТСЯ РАЗНЫМ: числа вырезаны, слова — нет.
            Assert.AreNotEqual(
                KvActionLog.ComposeKey("робот", "состояние", "включено"),
                KvActionLog.ComposeKey("робот", "состояние", "выключено"),
                "включение и выключение склеились в одно событие — журнал потеряет смену состояния");

            // ПОДТВЕРЖДЕНИЕ ЧЕРЕЗ НАСТОЯЩИЙ ЖУРНАЛ: три РАЗНЫЕ записи подряд — все три в памяти,
            // даже если пришли в одну и ту же секунду (отсечение не трогает разные события).
            //
            // ПОЧЕМУ СВОЙ ЭКЗЕМПЛЯР, А НЕ `Instance`. `KvActionLog.Instance` — ОБЩИЙ журнал
            // приложения, и он пишет в настоящий файл оператора. Тест, который добавляет в него
            // строки «самопроверка», засоряет ту самую запись, которую разбирает тестировщик, —
            // то есть тест портит улику, ради которой всё и делалось. Свой экземпляр пишет в тот
            // же каталог, но не трогает общий буфер и не влияет на другие тесты.
            KvActionLog log = new KvActionLog { capacity = 50, echoToConsole = false };
            log.ResetRepeatMemory();

            log.Add(KvLogKind.Ui, "самопроверка: событие А");
            log.Add(KvLogKind.Ui, "самопроверка: событие Б");
            log.Add(KvLogKind.Ui, "самопроверка: событие В");

            Assert.AreEqual(3, log.Count,
                "из трёх РАЗНЫХ событий в журнале осталось " + log.Count +
                " — отсечение повторов глотает разные строки");

            // А ТЕПЕРЬ ОБРАТНОЕ: три ОДИНАКОВЫХ подряд — в журнале ОДНА строка (окно действует).
            // Без этой половины проверка была бы односторонней: журнал, который пишет всё подряд,
            // тоже дал бы «3 из 3».
            log.Add(KvLogKind.Ui, "самопроверка: событие А");
            log.Add(KvLogKind.Ui, "самопроверка: событие А");
            log.Add(KvLogKind.Ui, "самопроверка: событие А");
            Assert.AreEqual(3, log.Count,
                "повторы одинакового события дописали строки: отсечение не работает в живом журнале");
        }
    }
