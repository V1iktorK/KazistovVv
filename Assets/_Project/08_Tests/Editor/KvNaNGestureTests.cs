//
//  ОТКУДА ЗАДАЧА. При проверке потери отслеживания нашёлся класс дефекта: в C# ЛЮБОЕ сравнение с
//  NaN даёт `false`. Поэтому проверки вида «дальше предела → отказ» НЕ СРАБАТЫВАЮТ для NaN — и
//  нечисловые данные проходят как «нормальные».
//
//  ЧТО НАЙДЕНО 30.10.2026:
//    • `KvXrControllerVisuals.IsPoseUsable` — NaN принимался как годная поза. Модель с такой
//      позицией Unity НЕ РИСУЕТ, то есть контроллер бесследно исчезал из мира;
//    • `KvGestureMath.IsHandInView` — жест с NaN-координатами МОЛЧА игнорировался: оператор делает
//      движение, панель не реагирует, ошибок нет.
//
//  ГДЕ БЕРЁТСЯ NaN: деление на ноль внутри рантайма при пересчёте системы координат — штатная
//  ситуация при потере отслеживания на части прошивок.
//
//  ЧТО ЗАКРЕПЛЯЕТСЯ:
//    1) нечисловая рука НЕ считается «в поле зрения»;
//    2) нечисловая голова НЕ даёт «в поле зрения» (проверяется отдельно: она второй аргумент);
//    3) обычная рука перед лицом — СЧИТАЕТСЯ (обратная ошибка тоже дефект);
//    4) рука далеко — не считается (базовая проверка, что функция вообще работает).
// ================================================================================================

using KazistovVvXr;
using NUnit.Framework;
using UnityEngine;

namespace KazistovVvTests
{
    /// <summary>Нечисловые данные в жестах: отказ, а не тихое «не сработало».</summary>
    public class KvNaNGestureTests
    {
        private static readonly Vector3 Head = new Vector3(0f, 1.6f, 0f);
        private static readonly Quaternion LookingForward = Quaternion.identity;

        // ---------------------------------------------------------------- 1. НЕЧИСЛОВАЯ РУКА

        /// <summary>
        /// РУКА С NaN НЕ СЧИТАЕТСЯ «В ПОЛЕ ЗРЕНИЯ». До исправления оба сравнения давали `false`
        /// (NaN не больше предела и NaN не меньше порога), поэтому функция отвечала «нет» —
        /// то есть жест просто не срабатывал, без единой ошибки. Теперь это ЯВНЫЙ отказ.
        /// </summary>
        [Test]
        public void NaNHand_IsNotInView()
        {
            var nanHand = new Vector3(float.NaN, 1.5f, 0.4f);

            Assert.IsFalse(KvGestureMath.IsHandInView(nanHand, Head, LookingForward),
                "рука с NaN признана видимой — по мусорным координатам может сработать жест");
        }

        /// <summary>Бесконечность в позиции руки — тоже отказ (после вычитания даст NaN).</summary>
        [Test]
        public void InfiniteHand_IsNotInView()
        {
            var infinite = new Vector3(float.PositiveInfinity, 1.5f, 0.4f);

            Assert.IsFalse(KvGestureMath.IsHandInView(infinite, Head, LookingForward),
                "рука с бесконечностью признана видимой");
        }

        // ---------------------------------------------------------------- 2. НЕЧИСЛОВАЯ ГОЛОВА

        /// <summary>
        /// ГОЛОВА С NaN — ОТДЕЛЬНАЯ ПРОВЕРКА. Позиция головы приходит от камеры; если она нечисловая,
        /// смещение «рука минус голова» тоже нечисловое, и вся проверка теряет смысл. Проверяется
        /// ОТДЕЛЬНО от руки, потому что это другой вход и его легко забыть.
        /// </summary>
        [Test]
        public void NaNHead_IsNotInView()
        {
            var head = new Vector3(float.NaN, 1.6f, 0f);
            var hand = new Vector3(0f, 1.5f, 0.3f);

            Assert.IsFalse(KvGestureMath.IsHandInView(hand, head, LookingForward),
                "нечисловая позиция ГОЛОВЫ не отсекается — проверка теряет смысл");
        }

        // ---------------------------------------------------------------- 3. НОРМА

        /// <summary>
        /// ОБЫЧНАЯ РУКА ПЕРЕД ЛИЦОМ — ВИДНА. Обратная ошибка («отсекаем всё») тоже дефект: тогда
        /// жесты не работают вообще, и оператор не понимает, почему панель не отвечает.
        /// </summary>
        [Test]
        public void NormalHandInFront_IsInView()
        {
            // Рука в 30 см перед лицом по направлению взгляда (вперёд = +Z).
            var hand = new Vector3(0f, 1.5f, 0.3f);

            Assert.IsTrue(KvGestureMath.IsHandInView(hand, Head, LookingForward),
                "обычная рука перед лицом признана невидимой — жесты не будут работать");
        }

        /// <summary>
        /// РУКА ДАЛЕКО — НЕ ВИДНА. Базовая проверка работоспособности: без неё «всё видно» проходило
        /// бы как «работает».
        /// </summary>
        [Test]
        public void FarHand_IsNotInView()
        {
            // Рука в 5 метрах: дальше предела от головы.
            var hand = new Vector3(0f, 1.6f, 5f);

            Assert.IsFalse(KvGestureMath.IsHandInView(hand, Head, LookingForward),
                "рука в 5 метрах признана видимой — проверка дальности не работает");
        }

        /// <summary>
        /// РУКА ЗА СПИНОЙ — НЕ ВИДНА. Проверяется направление, а не только расстояние: без этого
        /// жест срабатывал бы от движения за спиной.
        /// </summary>
        [Test]
        public void HandBehindBack_IsNotInView()
        {
            var hand = new Vector3(0f, 1.5f, -0.3f);      // позади (взгляд в +Z)

            Assert.IsFalse(KvGestureMath.IsHandInView(hand, Head, LookingForward),
                "рука за спиной признана видимой — жест сработает от движения за спиной");
        }
    }
}
