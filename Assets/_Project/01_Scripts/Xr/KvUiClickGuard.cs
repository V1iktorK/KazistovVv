namespace KazistovVvXr
{
    /// <summary>
    /// СТОРОЖ ПОВТОРНОГО ВХОДА В ОБРАБОТЧИК КНОПКИ — ЧИСТАЯ ЛОГИКА, ПРОВЕРЯЕМАЯ БЕЗ СЦЕНЫ.
    ///
    /// ОТКУДА ЗАДАЧА. Tombstone планшета Redmi (сборка 10.11.2026), SIGSEGV с пометкой
    /// «stack pointer is close to top of stack; likely stack overflow», 512 кадров, в которых
    /// ЧЕРЕДУЮТСЯ ДВА адреса `libil2cpp.so` — то есть бесконечная взаимная рекурсия, а не порча
    /// памяти. Последняя строка журнала перед падением ровно одна:
    /// <code>
    /// [KvUiSweep] press=KazistovVv_UI/KvFeatureCanvas/KvFeatureWindow/Header/Close«✕» type=Button …
    /// </code>
    /// То есть приложение убило себя нажатием на «✕» в шапке окна «Панель функций».
    ///
    /// НАЙДЕННАЯ ПРИЧИНА (взаимный вызов двух методов, а не «слишком глубокий стек»):
    /// <code>
    /// KvFeatureWindow.Hide()                      — обработчик кнопки «✕»
    ///   → KvWindowBelt.SendToBelt("panel.features")
    ///       → Entry.Hide()                      — ЭТО ТА ЖЕ САМАЯ `Hide`, положенная в реестр
    ///           → KvWindowBelt.SendToBelt("panel.features")   … и так до конца стека
    /// </code>
    /// Цикл замкнут на себя: `Hide` регистрируется в реестре окон как действие «скрыть»
    /// (`KvFeatureWindow.Build`, строка с `KvWindowBelt.Register`), а сама она первым делом зовёт
    /// реестр, который обязан вызвать зарегистрированное действие. Первый же «✕» не скрывает
    /// окно, а уходит в бесконечность.
    ///
    /// ПОЧЕМУ ЭТОГО НЕ ВИДНО В РЕДАКТОРЕ. В PlayMode на компьютере рекурсия тоже есть, но Unity
    /// ловит её своим сторожевым счётчиком и печатает `StackOverflowException` в консоль, а на
    /// устройстве в IL2CPP честного ограничителя глубины нет — процесс получает SIGSEGV и просто
    /// исчезает. Отсюда «нативное падение» в отчёте тестировщика и «не воспроизводится» у нас.
    ///
    /// ЧТО ЗДЕСЬ. Только ПРАВИЛО ответа на повторный вход и на повторное нажатие — без GameObject,
    /// без Canvas и без кадра. Окно передаёт свои флаги и получает ответ; поэтому правило можно
    /// проверить тестом без сцены, а не «на глаз в шлеме».
    /// </summary>
    public static class KvUiClickGuard
    {
        /// <summary>Можно ли ВООБЩЕ начинать действие (или надо молча выйти).</summary>
        public static bool CanStart(bool alreadyRunning)
        {
            return !alreadyRunning;
        }

        /// <summary>
        /// НАДО ЛИ ВЫПОЛНЯТЬ ДЕЙСТВИЕ ПОВТОРНО. Второе нажатие на то же действие подряд —
        /// это НЕ новое намерение оператора, а повтор события (пересборка панели в том же кадре,
        /// повторная доставка клика, программный вызов «на всякий случай»).
        ///
        /// ПОЧЕМУ ОТКАЗ, А НЕ ПОВТОР. Для «скрыть окно» и «пересобрать окно» повтор не даёт
        /// ничего видимого, зато платит полную цену пересборки содержимого и сбрасывает выбор
        /// оператора. Отказ здесь — это и есть «второй раз не пересобираем».
        /// </summary>
        public static bool ShouldRun(bool sameActionAlreadyDone)
        {
            return !sameActionAlreadyDone;
        }
    }

    /// <summary>
    /// РАЗРЫВ ЦИКЛА «САМ СЕБЯ ЗОВУ» ДЛЯ ОКНА, ЗАРЕГИСТРИРОВАННОГО В РЕЕСТРЕ ОКОН.
    ///
    /// ЧТО БЫЛО. `KvFeatureWindow.Hide()` — это И обработчик кнопки «✕», И действие «скрыть»,
    /// которое окно кладёт в реестр `KvWindowBelt` при сборке. Поэтому первая же строка `Hide`
    /// («отдать себя в реестр, чтобы лечь на пояс») вызывала ровно `Hide` — взаимная рекурсия
    /// `Hide → SendToBelt → entry.Hide → Hide`. Стек кончается, IL2CPP получает SIGSEGV:
    /// приложение падает от нажатия на крестик.
    ///
    /// ЧЕМ ПЛОХО БЫЛО БЫ ЗАГЛУШИТЬ ФЛАГОМ. Флаг «уже закрываюсь» на время вызова погасил бы
    /// симптом и в этом окне, но причину — взаимный вызов двух методов, один из которых обязан
    /// звать другой, — оставил бы. Любой новый вызывающий (горячая клавиша, команда меню,
    /// пояс, диагностика) снова попал бы в тот же цикл при малейшей правке порядка строк.
    ///
    /// ЧТО СТАЛО. Цикл РАЗОРВАН по построению: у окна один вход `Hide()`, и он НЕ зовёт реестр.
    /// Реестр (и только он) зовёт окно, когда кладёт его на пояс. Два шага пронумерованы и
    /// передают «я уже иду в реестр» флагом `inBeltDispatch`, который снимается в конце
    /// (`try/finally`) — он существует НЕ как лечение, а как страховка от повторного входа,
    /// пока реестр вызывает окно. Порядок здесь — часть контракта, поэтому он в чистой функции:
    /// тест проверяет именно его, а не текст исходника.
    /// </summary>
    public enum KvHideStep
    {
        /// <summary>Окно скрывает себя САМО (SetActive(false)/visible=false) и НЕ зовёт реестр.</summary>
        HideItself = 0,

        /// <summary>Окно просит реестр положить его на пояс — реестр скроет его своим вызовом.</summary>
        SendToBelt = 1
    }

    public static class KvHideSequence
    {
        /// <summary>Порядок шагов закрытия окна, зарегистрированного в реестре пояса.</summary>
        public static readonly KvHideStep[] Registered =
        {
            KvHideStep.HideItself,
            KvHideStep.SendToBelt
        };

        /// <summary>
        /// ЗАКОННЫЙ ЛИ ЭТО ПОРЯДОК. Незарегистрированное окно (`registered == false`) шага «на пояс»
        /// не имеет вовсе — ему остаётся только скрыть себя. Это НЕ ослабление проверки: любое
        /// окно, зарегистрированное в реестре, обязано иметь оба шага и именно в этом порядке.
        /// </summary>
        public static bool IsValidOrder(KvHideStep[] steps, bool registered)
        {
            if (registered) return IsRegisteredOrder(steps);
            return steps != null && steps.Length == 1 && steps[0] == KvHideStep.HideItself;
        }

        /// <summary>Ровно два шага и именно в порядке «сначала себя, потом на пояс».</summary>
        public static bool IsRegisteredOrder(KvHideStep[] steps)
        {
            if (steps == null || steps.Length != Registered.Length) return false;
            for (int i = 0; i < Registered.Length; i++)
                if (steps[i] != Registered[i]) return false;
            return true;
        }

        /// <summary>
        /// МОЖНО ЛИ ЗОВАТЬ РЕЕСТР ИЗНУТРИ ОКНА. Ответ всегда «нет», когда реестр уже вызывает это
        /// окно (`registryCallingWindow == true`): именно этот повтор и есть вход в цикл.
        /// </summary>
        public static bool MayAskRegistry(bool registryCallingWindow)
        {
            return !registryCallingWindow;
        }
    }
}
