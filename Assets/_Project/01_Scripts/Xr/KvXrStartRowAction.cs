namespace KazistovVvXr
{
    /// <summary>ЧТО ДЕЛАЕТ СТРОКА СТАРТОВОГО МЕНЮ (§42).</summary>
    public enum KvXrStartRowAction
    {
        /// <summary>Ничего (строка ещё не размечена).</summary>
        None = 0,

        /// <summary>Выбрать существующий объект сцены (стол или робота).</summary>
        SelectObject = 1,

        /// <summary>Создать квадратный стол 0,72 × 0,48 м.</summary>
        CreateSquareTable = 2,

        /// <summary>Создать круглый «авто» стол.</summary>
        CreateAutoTable = 3,

        /// <summary>Создать 6-осевого робота.</summary>
        CreateSixAxisRobot = 4,

        /// <summary>Создать SCARA.</summary>
        CreateScaraRobot = 5,

        /// <summary>Существующая строка «Запустить стенд (добавить стол и роботов)».</summary>
        RunStand = 6,

        /// <summary>Существующая строка «Сменить робота».</summary>
        SwitchRobot = 7,

        /// <summary>
        /// СТРОКА «МОДЕЛЬ РОБОТА: …» (часть 3 задачи владельца 02.11.2026).
        ///
        /// СЛОВА ВЛАДЕЛЬЦА: «роботов всех перенеси» + выбранный вариант «Выбор из списка —
        /// один активный».
        ///
        /// КАК РАБОТАЕТ. В разделе «Робот» после штатных строк идёт по строке на каждую модель
        /// каталога `KvRobotCatalog`. Номер модели вычисляется из индекса строки (см.
        /// `KvXrStartMenuRows.ModelIndexForRow`), поэтому само действие одно на все модели —
        /// иначе enum пришлось бы править при каждом новом роботе.
        /// </summary>
        CreateRobotFromModel = 8,

        /// <summary>
        /// СТРОКА «ДВУРУКИЙ: OpenArm» (часть 4 задачи владельца).
        ///
        /// Отдельное действие, а не просто ещё одна модель: двурукий ставит НЕ шестиосевой
        /// контроллер, а `KvDualArmController` с двумя цепочками. Смешать их в одном действии
        /// означало бы, что вторая рука останется мёртвой.
        /// </summary>
        CreateDualArmRobot = 9
    }
}
