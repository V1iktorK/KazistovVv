using UnityEngine;

namespace KazistovVvXr
{
    /// <summary>
    /// ГДЕ СТАВИТЬ АНГАР В XR-СЦЕНЕ (сессия §35, карточка Б17).
    ///
    /// ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП. «Поставить ангар рядом со стендами» — это ЧИСЛО, а не картинка,
    /// и ошибиться в нём легко на десятки метров: ангар проекта — зал 37,8 × 50,3 м при потолке
    /// 9,4 м, и промах означает либо «ангар в стороне от оператора», либо «оператор внутри стены».
    /// Здесь лежит только арифметика размещения; объекты сцены создаёт редакторный инструмент
    /// `KvXrHangarTools`, а правило проверяется тестом без шлема и без сцены.
    ///
    /// ОТКУДА ЧИСЛА. Измерено, а не подобрано: редакторный метод
    /// `KvXrHangarTools.MeasureDesktopEnvironment` (журнал `Logs\s35-hangar-measure3.log`,
    /// 16.10.2026) вернул габарит ангара (40,18 × 9,38 × 50,31), его центр (10,91; 4,69; −15,00),
    /// центр стендов (0,00; 1,30; −26,00) и **масштаб корней 1,000** — то есть геометрия проекта
    /// метрическая и подбирать масштаб «на глаз» нельзя и не нужно ([S3.6]).
    ///
    /// ЧИСЛА ПЕРЕМЕРЕНОВЫ, И ЭТО ВАЖНО. Первый замер дал по X **37,77 м** и «17 корней», и это
    /// было НЕВЕРНО: правило имён измерителя требовало точного равенства `name == "Floor"` и потому
    /// видело одну плиту пола из шестнадцати, а плиты зала доходят до x = 31. Ошибка вскрылась
    /// сравнением с габаритом, который дал инструмент постановки (он ставит все 32 объекта и видит
    /// 40,18 м). Число «37,77» уже лежало в заготовке как готовое «доказательство» — и было бы
    /// предъявлено владельцу как факт. Здесь стоит переме́ренное значение, а измеритель исправлен.
    ///
    /// ГЛАВНОЕ ПРАВИЛО (одна строка, из которой следует всё остальное):
    ///     положение корня ангара = центр стендов в XR − центр стендов на компьютере.
    /// Почему так: корень ангара на компьютере стоит в начале координат, а стенды — в
    /// (0; 1,30; −26,00). Сдвинув корень на разницу, мы получаем ЗЕРКАЛЬНО ту же картину:
    /// стенды занимают внутри зала ровно то место, что и на компьютере. Отсюда автоматически
    /// следует и то, что смещение центра ангара от центра стендов остаётся прежним — (10,91; 3,39; 11,00).
    /// </summary>
    public static class KvHangarPlacement
    {
        // ==================================================== ИЗМЕРЕННЫЕ ЧИСЛА (не менять «на глаз»)

        /// <summary>Габарит ангара на компьютере, метры (40,18 × 9,38 × 50,31).</summary>
        public static readonly Vector3 DesktopHangarSize = new Vector3(40.18f, 9.38f, 50.31f);

        /// <summary>Центр габарита ангара на компьютере, метры.</summary>
        public static readonly Vector3 DesktopHangarCenter = new Vector3(10.91f, 4.69f, -15.00f);

        /// <summary>Центр габарита стендов на компьютере, метры.</summary>
        public static readonly Vector3 DesktopStandsCenter = new Vector3(0.00f, 1.30f, -26.00f);

        /// <summary>Центр габарита стендов В КООРДИНАТАХ КОРНЯ АНГАРА (корень стоит в начале координат).</summary>
        public static readonly Vector3 HangarLocalCenter = DesktopHangarCenter;

        /// <summary>
        /// МАСШТАБ КОРНЯ АНГАРА. Ровно 1,0 — измеренный масштаб префабов ангара.
        /// Единица берётся не «по смыслу», а из измерения: иначе зал превратился бы в игрушечный
        /// или в километровый.
        /// </summary>
        public const float RootScale = 1f;

        /// <summary>Ниже этого зал уже не «помещение вокруг оператора» — проверка для теста.</summary>
        public const float MinCeilingMeters = 2.2f;

        // ==================================================== ПРАВИЛА

        /// <summary>Смещение центра ангара от центра стендов на компьютере — (9,71; 3,39; 11,00).</summary>
        public static Vector3 DesktopOffset
        {
            get { return DesktopHangarCenter - DesktopStandsCenter; }
        }

        /// <summary>
        /// ГДЕ ОПЕРАТОР СТОИТ ВНУТРИ ЗАЛА — в координатах корня зала, метры. Значение −29,20
        /// не выдумано: именно при нём владелец 16.10.2026 посмотрел в шлем и подтвердил
        /// «вижу помещение: стены, потолок, пол ангара». Это проверенная точка, и она держится.
        /// </summary>
        public static readonly Vector3 ApprovedOperatorLocalPosition = new Vector3(0f, 0f, -29.20f);

        /// <summary>
        /// СДВИГ ВСЕЙ ЛАБОРАТОРИИ НА ОПЕРАТОРА. Владелец 16.10.2026: «сверь координаты робота
        /// в desktop версии» — и это правильное указание. В десктопной сцене лаборатория стоит
        /// в своих координатах: камера (0; 2; −28), стенды (0; 0; −20,7) и (0; 0; −31,3), роботы
        /// на столешницах. Чтобы в шлеме было «как на компьютере», НИЧЕГО не переставляется:
        /// вся лаборатория вместе с залом сдвигается ОДНИМ смещением так, чтобы ЦЕНТР СТЕНДОВ
        /// оказался ровно там, где стоит оператор.
        ///
        /// ЦЕНТР СТЕНДОВ — ЭТО ЗАЗОР МЕЖДУ ДВУМЯ СТОЛАМИ (1 м), то есть оператор встаёт МЕЖДУ
        /// столами: стол впереди, стол позади, столешницы на 0,98 м — примерно по пояс.
        /// Именно поэтому в десктопной сцене центр лаборатории и есть −26,0.
        ///
        /// ЧЕГО ЭТО НЕ ДЕЛАЕТ: не переставляет столы «влево-вправо», не меняет зазор и расстояние
        /// между столами, не двигает зал относительно столов. Относительное расположение зала,
        /// столов и роботов остаётся РОВНО десктопным — меняется только точка отсчёта.
        /// </summary>
        public static Vector3 LabShiftToOperator
        {
            get { return new Vector3(-DesktopStandsCenter.x, 0f, -DesktopStandsCenter.z); }
        }

        /// <summary>Точка лаборатории в координатах десктопной сцены → её место в XR-сцене.</summary>
        public static Vector3 ShiftToOperator(Vector3 desktopPosition)
        {
            return desktopPosition + LabShiftToOperator;
        }

        /// <summary>
        /// ПОЛОЖЕНИЕ КОРНЯ ЗАЛА ПО ОПЕРАТОРУ. Зал на компьютере стоит в начале координат, значит
        /// в шлеме он встаёт на тот же сдвиг, что и вся лаборатория, — иначе зал и столы разъехались бы.
        /// </summary>
        public static Vector3 RootPositionForOperator(Vector3 operatorBasePosition)
        {
            return new Vector3(operatorBasePosition.x, 0f, operatorBasePosition.z) + LabShiftToOperator;
        }

        /// <summary>
        /// ПОЛОЖЕНИЕ КОРНЯ ЗАЛА ПО СТЕНДАМ. Оставлено для сверки и отчёта: показывает, куда
        /// поехал бы зал, если бы его по-прежнему привязывали к столам.
        /// </summary>
        public static Vector3 RootPosition(Vector3 standsCenterXr)
        {
            return standsCenterXr - DesktopStandsCenter;
        }

        /// <summary>
        /// МИРОВОЙ ГАБАРИТ ЗАЛА при данном положении корня. Корень ангара стоит не в центре
        /// габарита (в этом и была бы ошибка «на глаз»), поэтому центр габарита считается
        /// как «положение корня + измеренный центр в его координатах».
        /// </summary>
        public static Bounds BoundsAt(Vector3 rootPosition)
        {
            return new Bounds(rootPosition + HangarLocalCenter, DesktopHangarSize);
        }

        /// <summary>Габарит зала в XR-сцене при измеренном центре стендов этой сцены.</summary>
        public static Bounds BoundsForStands(Vector3 standsCenterXr)
        {
            return BoundsAt(RootPosition(standsCenterXr));
        }

        /// <summary>Лежит ли точка внутри зала (запас — чтобы «внутри» не значило «вплотную к стене»).</summary>
        public static bool Contains(Vector3 rootPosition, Vector3 worldPoint, float marginMeters = 0f)
        {
            Bounds b = BoundsAt(rootPosition);
            Vector3 half = b.extents - Vector3.one * Mathf.Max(0f, marginMeters);
            if (half.x <= 0f || half.y <= 0f || half.z <= 0f) return false;

            Vector3 d = worldPoint - b.center;
            return Mathf.Abs(d.x) <= half.x && Mathf.Abs(d.y) <= half.y && Mathf.Abs(d.z) <= half.z;
        }

        /// <summary>Потолок зала при данном положении корня, метры над полом.</summary>
        public static float CeilingMeters(Vector3 rootPosition)
        {
            Bounds b = BoundsAt(rootPosition);
            return b.max.y;
        }

        /// <summary>
        /// ПОЛ ЗАЛА. Плиты ангара лежат на y = 0 (корень в начале координат), поэтому при переносе
        /// пол зала должен оказаться на уровне пола сцены, иначе оператор «провалится» или «всплывёт».
        /// </summary>
        public static float FloorHeight(Vector3 rootPosition)
        {
            return rootPosition.y;
        }

        /// <summary>
        /// СТРОКА ЖУРНАЛА: одна строка на всю постановку окружения. Без неё «стало лучше» не
        /// считается ([S3.7]).
        ///
        /// ЧИСЛА ПЕЧАТАЮТСЯ С ИНВАРИАНТНОЙ КУЛЬТУРОЙ, и это не придирка. По умолчанию
        /// `string.Format` берёт культуру системы: на русской Windows он даёт «37,77», а соседние
        /// `Vector3.ToString` в той же строке — «(0.00, 0.00, 29.20)». В одной строке оказывались
        /// РАЗНЫЕ разделители, и одна и та же сборка в шлеме (локаль устройства) и на компьютере
        /// печатала разные числа. Строка журнала — это ДОКАЗАТЕЛЬСТВО, и её числа обязаны
        /// находиться поиском одинаково везде.
        /// </summary>
        public static string Describe(Vector3 standsCenterXr, Vector3 rootPosition)
        {
            Bounds b = BoundsAt(rootPosition);
            Vector3 check = b.center - standsCenterXr;
            return string.Format(System.Globalization.CultureInfo.InvariantCulture,
                "окружение: ангар {0:0.00}×{1:0.00}×{2:0.00} м · корень {3} · пол {4:0.00} м · потолок {5:0.00} м · " +
                "масштаб {6:0.000} · смещение центра зала от центра стендов ({7:0.00}, {8:0.00}, {9:0.00})",
                b.size.x, b.size.y, b.size.z,
                rootPosition.ToString("0.00"),
                FloorHeight(rootPosition), CeilingMeters(rootPosition),
                RootScale,
                check.x, check.y, check.z);
        }
    }
}
