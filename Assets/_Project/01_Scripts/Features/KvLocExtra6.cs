    /// тестом `KvXrOverlayTests.OverlayStrings_HaveXrKeys`: у КАЖДОГО ключа обязан быть префикс
    /// `xr.`. Дописать туда `bt.open` значит сломать тест, который защищает оверлей. Прогон
