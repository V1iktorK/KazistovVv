    public static class KvLocExtra6
    {
        private static bool installed;
        private static int registered;

        /// <summary>Сколько строк зарегистрировано модулем (диагностика).</summary>
        public static int RegisteredCount { get { return registered; } }

        /// <summary>Сколько строк в таблице модуля.</summary>
        public static int RowCount { get { return Rows.Length; } }

        /// <summary>Ключ строки по номеру (для тестов полноты).</summary>
        public static string KeyAt(int index)
        {
            if (index < 0 || index >= Rows.Length) return "";
            return Rows[index] != null && Rows[index].Length > 0 ? Rows[index][0] : "";
        }

        /// <summary>Текст строки на языке по номеру (0 — ru, 1 — en, … 6 — ja).</summary>
        public static string TextAt(int index, int language)
        {
            if (index < 0 || index >= Rows.Length) return "";
            string[] row = Rows[index];
            if (row == null || language < 0 || language + 1 >= row.Length) return "";
            return row[language + 1];
        }

        /// <summary>Сколько языков заполнено у строки.</summary>
        public static int LanguageCount(int index)
        {
            if (index < 0 || index >= Rows.Length) return 0;
            string[] row = Rows[index];
            if (row == null) return 0;
            int count = 0;
            for (int i = 1; i < row.Length; i++) if (!string.IsNullOrEmpty(row[i])) count++;
            return count;
        }

        /// <summary>
        /// Зарегистрировать строки. Внешние словари главнее: если ключ есть в JSON, значение
        /// отсюда его НЕ перекрывает (`KvLoc.Has`) — ровно как у остальных модулей.
        /// </summary>
        public static void Install()
        {
            if (installed) return;
            installed = true;

            int count = 0;
            for (int r = 0; r < Rows.Length; r++)
            {
                string[] row = Rows[r];
                if (row == null || row.Length < 1 + KvLocExtra.Codes.Length) continue;
                string key = row[0];
                if (string.IsNullOrEmpty(key) || KvLoc.Has(key)) continue;

                bool wrote = false;
                for (int c = 0; c < KvLocExtra.Codes.Length; c++)
                {
                    string text = row[c + 1];
                    if (string.IsNullOrEmpty(text)) continue;
                    KvLoc.AddRuntimeStrings(KvLocExtra.Codes[c], key, text);
                    wrote = true;
                }
                if (wrote) count++;
            }
            registered = count;
            UnityEngine.Debug.Log("[Loc] строки, которых не было в словарях, зарегистрированы: " + count +
                                  " · всего в словарях: " + KvLoc.TotalStrings);
        }

