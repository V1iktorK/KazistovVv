    /// ПРО ПЕРЕВОДЫ. Русский текст — из fallback того места, где ключ запрашивается (то есть
    /// он не выдуман). Остальные шесть языков заполнены тем же текстом ОСОЗНАННО: пока перевода
    /// нет, оператор увидит понятную строку, а не пустую ячейку, и долг будет виден в отчёте,
    /// а не спрятан за `Assert.Ignore`. `LOCALIZATION_AUDIT.md` — место, где этот список
    /// сокращается по мере перевода.
