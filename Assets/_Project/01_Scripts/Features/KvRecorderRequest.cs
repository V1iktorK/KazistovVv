namespace KazistovVvFeatures
{
    /// <summary>Что именно должен записать рекордер: файл без расширения и параметры видео.</summary>
    public struct KvRecorderRequest
    {
        /// <summary>Путь к будущему MP4 БЕЗ расширения (его добавляет рекордер).</summary>
        public string pathWithoutExtension;

        /// <summary>Ширина кадра (0 — взять из вида игры).</summary>
        public int width;

        /// <summary>Высота кадра (0 — взять из вида игры).</summary>
        public int height;

        /// <summary>Кадров в секунду.</summary>
        public int fps;

        /// <summary>Битрейт видео, кбит/с.</summary>
        public int bitrateKbps;
    }
}