using UnityEngine;

namespace KazistovVvUI
{
    /// <summary>
    /// ПОДПИСЬ РЕЖИМА ДЛЯ ОПЕРАТОРА (создано 30.10.2026, S44, пункт 5.19 плана).
    ///
    /// ЗАЧЕМ. В режиме камеры системный курсор скрыт, панели недоступны, а камера слушается мыши.
    /// В режиме интерфейса — наоборот. Раньше переключение (TAB, §26) НИЧЕМ не показывалось:
    /// оператор нажимал TAB, курсор пропадал, и понять, «почему не нажимаются кнопки» и «почему
    /// камера крутится за мышью» можно было только по памяти. Это и записано в плане (5.19).
    ///
    /// ЧТО ЗДЕСЬ. Только ТЕКСТ и НАЗВАНИЕ ЦВЕТА — без сцены, без UI, без вызовов отрисовки.
    /// Так подпись можно проверить тестом: важно, чтобы в ней было НАЗВАНИЕ РЕЖИМА и ПОДСКАЗКА,
    /// как из него выйти. Пропадёт подсказка — оператор снова останется без выхода.
    ///
    /// ПОЧЕМУ ОТДЕЛЬНЫЙ КЛАСС. Если писать строку прямо в месте отрисовки, её нельзя ни проверить,
    /// ни перевести на семь языков (а проект многоязычный). Здесь строка идёт через `KvLoc`.
    /// </summary>
    public static class KvModeIndicator
    {
        /// <summary>
        /// НАЗВАНИЕ РЕЖИМА ДЛЯ ПОДПИСИ. Коротко: подпись живёт в углу экрана и не должна мешать.
        /// </summary>
        public static string Title(KvCursorMode mode)
        {
            return mode == KvCursorMode.CameraMode
                ? KvLoc.T("mode.camera", "КАМЕРА")
                : KvLoc.T("mode.ui", "ИНТЕРФЕЙС");
        }

        /// <summary>
        /// ЧТО ДЕЛАЕТ РЕЖИМ — одной строкой. Оператор должен понимать не «как называется», а
        /// «что сейчас будет с мышью».
        /// </summary>
        public static string Hint(KvCursorMode mode)
        {
            return mode == KvCursorMode.CameraMode
                ? KvLoc.T("mode.camera.hint", "мышь вращает камеру · панели не нажимаются")
                : KvLoc.T("mode.ui.hint", "мышь двигает курсор · панели нажимаются");
        }

        /// <summary>
        /// КАК ВЫЙТИ ИЗ РЕЖИМА. Без этой строки индикатор бесполезен: он сообщает состояние, но не
        /// способ его изменить — а именно этого оператор и не знал (пункт 5.19).
        /// </summary>
        public static string ExitHint()
        {
            return KvLoc.T("mode.toggle", "TAB — переключить") + " · " + KvMouseCursor.ModeToggleKey;
        }

        /// <summary>ПОЛНАЯ ПОДПИСЬ: «КАМЕРА · мышь вращает камеру · панели не нажимаются · TAB — переключить · Tab».</summary>
        public static string Line(KvCursorMode mode)
        {
            return Title(mode) + " · " + Hint(mode) + " · " + ExitHint();
        }

        /// <summary>
        /// ЦВЕТ ПОДПИСИ. Режимы должны различаться СРАЗУ, без чтения: камера — спокойный синеватый,
        /// интерфейс — тёплый зелёный. Возвращается `Color`, чтобы отрисовка не изобретала свои
        /// значения в двух местах (и не разошлась с тестом).
        /// </summary>
        public static Color Tint(KvCursorMode mode)
        {
            return mode == KvCursorMode.CameraMode
                ? new Color(0.55f, 0.75f, 1f, 0.95f)
                : new Color(0.55f, 1f, 0.65f, 0.95f);
        }

        /// <summary>
        /// СТРОКА ДЛЯ ЖУРНАЛА. Отдельно от подписи на экране: в журнале нужны слова, а не цвет и не
        /// сокращения — по журналу потом разбирают, «почему не нажималось».
        /// </summary>
        public static string LogLine(KvCursorMode mode)
        {
            return "режим: " + (mode == KvCursorMode.CameraMode
                ? "камера (курсор скрыт, мышь вращает камеру)"
                : "интерфейс (курсор виден, панели доступны)") +
                " · выход — " + KvMouseCursor.ModeToggleKey;
        }
    }
}
