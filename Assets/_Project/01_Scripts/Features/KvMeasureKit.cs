using UnityEngine;

namespace KazistovVvUI
{
    /// <summary>
    /// ИЗМЕРЕНИЕ И СЕТКА РАБОЧЕЙ ЗОНЫ — ЧИСТАЯ ГЕОМЕТРИЯ, БЕЗ СЦЕНЫ
    /// (создано 30.10.2026, сессия S44).
    ///
    /// ЗАЧЕМ. В интерфейсе два пункта меню — «Сервис/Инструменты/Измерение» и «Сетка рабочей
    /// зоны» — были зарегистрированы ЗАГЛУШКАМИ (`Stub = true`) с подписью «пункт задел»: кнопки
    /// есть, а нажатие честно отвечает «в разработке». Оператору это ничего не даёт, а
    /// разработчику — создаёт видимость готового пункта.
    ///
    /// ЧТО ЗДЕСЬ. Ровно то, что нужно обоим пунктам, и ничего больше:
    ///   • расстояние между точками прицела и его проекции по осям — это и есть «линейка»;
    ///   • шаг и число линий сетки на столешнице — это «сетка рабочей зоны».
    ///
    /// ПОЧЕМУ ОТДЕЛЬНЫМ КЛАССОМ И БЕЗ UNITY-СЦЕНЫ. Измерение и раскладка сетки — арифметика.
    /// Если писать их прямо в обработчике команды, проверить можно только «кнопка не падает»;
    /// арифметику же проверяют тесты, и именно там ловятся ошибки знака, единиц и округления.
    /// </summary>
    public static class KvMeasureKit
    {
        /// <summary>
        /// РАССТОЯНИЕ МЕЖДУ ДВУМЯ ТОЧКАМИ (м). Это и есть показание линейки.
        ///
        /// Отдельный метод, а не `Vector3.Distance` на месте: у него есть ПРАВИЛО — округление
        /// до миллиметра в строке и «—» при отсутствии второй точки. Округление живёт здесь,
        /// чтобы показание в интерфейсе и в журнале не расходилось.
        /// </summary>
        public static float Distance(Vector3 a, Vector3 b)
        {
            return Vector3.Distance(a, b);
        }

        /// <summary>
        /// ПРОЕКЦИИ РАССТОЯНИЯ ПО ОСЯМ (по модулю). Оператору нужно не только «сколько», но и
        /// «насколько сдвинуто вбок/вверх»: при установке стола важна высота, при замере стоек —
        /// горизонтальный сдвиг. По модулю, потому что направление показывает картинка, а знак
        /// в подписи только мешает читать.
        /// </summary>
        public static Vector3 DeltaAbs(Vector3 a, Vector3 b)
        {
            Vector3 d = b - a;
            return new Vector3(Mathf.Abs(d.x), Mathf.Abs(d.y), Mathf.Abs(d.z));
        }

        /// <summary>
        /// СТРОКА ПОКАЗАНИЯ ЛИНЕЙКИ: «1,234 м (X 0,250 · Y 1,200 · Z 0,100)».
        ///
        /// ЧИСЛА — ЧЕРЕЗ INVARIANT CULTURE. На машине с русской локалью `ToString("0.000")` даёт
        /// запятую, а эти же числа нужны в журнале и в отчёте, где их сравнивают с эталоном.
        /// Поймано прогоном тестов 30.10.2026 на другой строке — здесь сделано сразу правильно.
        /// </summary>
        public static string Describe(Vector3 a, Vector3 b)
        {
            var c = System.Globalization.CultureInfo.InvariantCulture;
            Vector3 d = DeltaAbs(a, b);
            return Distance(a, b).ToString("0.000", c) + " м (X " + d.x.ToString("0.000", c) +
                   " · Y " + d.y.ToString("0.000", c) + " · Z " + d.z.ToString("0.000", c) + ")";
        }

        /// <summary>
        /// ШАГ СЕТКИ, ПОДОБРАННЫЙ ПО РАЗМЕРУ СТОЛЕШНИЦЫ. Идея простая: на столе 1×0,7 м сетка
        /// по 10 см даёт 10×7 клеток — читаемо; на столе 14×9 м (виртуальные стенды проекта) те же
        /// 10 см дали бы 140×90 линий — это уже не сетка, а заливка. Поэтому шаг растёт с размером.
        ///
        /// РЯД ШАГОВ ВЫБРАН «ЧЕЛОВЕЧЕСКИМ» (10 см → 20 → 50 → 1 м → 2 → 5), а не «оптимальным по
        /// формуле»: оператор должен узнавать клетку с первого взгляда.
        /// </summary>
        /// <param name="largestSideMeters">длина большей стороны области</param>
        /// <param name="maxLines">сколько линий допустимо на сторону (по умолчанию 20)</param>
        public static float GridStep(float largestSideMeters, int maxLines = 20)
        {
            float[] steps = { 0.1f, 0.2f, 0.5f, 1f, 2f, 5f, 10f, 20f, 50f };
            int limit = Mathf.Max(2, maxLines);
            if (largestSideMeters <= 0f) return steps[0];

            for (int i = 0; i < steps.Length; i++)
            {
                if (largestSideMeters / steps[i] <= limit) return steps[i];
            }
            return steps[steps.Length - 1];
        }

        /// <summary>
        /// СКОЛЬКО ЛИНИЙ СЕТКИ НА СТОРОНЕ ДЛИНОЙ `side` ПРИ ШАГЕ `step`.
        ///
        /// ВКЛЮЧАЯ ГРАНИЦЫ: сетка на столе 1,0 м с шагом 0,25 м даёт линии в 0 / 0,25 / 0,5 /
        /// 0,75 / 1,0 — это ПЯТЬ линий, а не четыре. Крайние линии нужны: по ним оператор
        /// совмещает сетку с краем стола.
        /// </summary>
        public static int GridLines(float side, float step)
        {
            if (step <= 0.0001f || side <= 0f) return 0;
            return Mathf.FloorToInt(side / step + 0.0001f) + 1;
        }

        /// <summary>
        /// ПОДПИСЬ СЕТКИ ДЛЯ ЖУРНАЛА: «сетка 1,000 × 0,700 м · шаг 0,100 м · 11 × 8 линий».
        /// По ней видно, что команда действительно построила сетку, а не «выполнилась успешно».
        /// </summary>
        public static string DescribeGrid(float width, float height, int maxLines = 20)
        {
            var c = System.Globalization.CultureInfo.InvariantCulture;
            float step = GridStep(Mathf.Max(width, height), maxLines);
            return "сетка " + width.ToString("0.000", c) + " × " + height.ToString("0.000", c) +
                   " м · шаг " + step.ToString("0.000", c) + " м · " +
                   GridLines(width, step) + " × " + GridLines(height, step) + " линий";
        }
    }
}
