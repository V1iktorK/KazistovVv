// ================================================================================================
//  KvDockGeometry.cs — ГЕОМЕТРИЯ DOCK-ПАНЕЛИ: «ПОКАЗАНА» ПРОТИВ «ВИДНА» (задача R6-1, 11.11.2026).
//
//  ОТКУДА ЗАДАЧА. На планшете (режим AR) команда «Настройки» ЛОГИРУЕТСЯ как выполненная, но панель
//  на экране не появляется — снимки до и после совпадают. В редакторе тот же путь проходит
//  (Е2Е 29/29), поэтому дефект виден только на устройстве.
//
//  КОРЕНЬ ПРОБЛЕМЫ — СМЕШЕНИЕ ДВУХ РАЗНЫХ ПОНЯТИЙ:
//    • `Show` — у объекта панели включён `activeSelf` (флаг в иерархии);
//    • `Видна` — панель реально попадает в кадр: ненулевой размер и пересечение с экраном.
//  Вопрос «показать или скрыть по повторному нажатию» нельзя решать по флагу: панель может быть
//  «показана» и при этом лежать за пределами экрана — тогда первое нажатие её ЗАКРЫВАЕТ, и
//  оператор видит ровно то, что описано в дефекте: команда выполнена, панели нет.
//
//  ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ И ЧИСТЫЕ ФУНКЦИИ. Геометрия — арифметика на четырёх числах: её можно
//  проверить тестом без сцены, без Unity-редактора и без устройства. Именно так задачу и надо
//  закрывать: тест, который падал бы на старом коде (там решения принимались по `activeSelf`).
// ================================================================================================

using UnityEngine;

namespace KazistovVvUI
{
    /// <summary>Чистая геометрия «видна ли панель на экране». Без сцены и без MonoBehaviour.</summary>
    public static class KvDockGeometry
    {
        /// <summary>
        /// Минимальная доля площади панели, которая обязана попасть в экран, чтобы панель считалась
        /// видимой. Не 0: панель, у которой виден один пиксель в углу, оператору бесполезна, и
        /// решать по ней «уже открыта» — значит снова закрывать её вместо показа.
        /// 0,10 — щадящий порог: у панели, стоящей на своём месте, в экран попадает практически
        /// всё, а у «уехавшей» — почти ничего.
        /// </summary>
        public const float MinVisibleFraction = 0.10f;

        /// <summary>
        /// ПЕРЕСЕЧЕНИЕ ПРЯМОУГОЛЬНИКА ПАНЕЛИ С ЭКРАНОМ — площадь, а не факт касания.
        ///
        /// `rect` — прямоугольник панели в координатах её родителя (как у `RectTransform.rect`),
        /// `screen` — размер экрана в тех же единицах. Функция терпима к отрицательным размерам:
        /// такие прямоугольники дают 0, а не «минус на минус».
        /// </summary>
        public static float IntersectionArea(Rect rect, Vector2 screen)
        {
            float w = Mathf.Abs(rect.width);
            float h = Mathf.Abs(rect.height);
            if (w <= 0f || h <= 0f || screen.x <= 0f || screen.y <= 0f) return 0f;

            float left = Mathf.Max(rect.xMin, 0f);
            float right = Mathf.Min(rect.xMax, screen.x);
            float bottom = Mathf.Max(rect.yMin, 0f);
            float top = Mathf.Min(rect.yMax, screen.y);
            if (right <= left || top <= bottom) return 0f;
            return (right - left) * (top - bottom);
        }

        /// <summary>
        /// ВИДНА ЛИ ПАНЕЛЬ. Три условия, каждое из которых само по себе даёт «не видна»:
        /// нулевой размер (панель свернули в ничто), отсутствие пересечения с экраном (уехала),
        /// и пересечение меньше `MinVisibleFraction` площади (виден уголок).
        /// </summary>
        public static bool IsVisibleOnScreen(Rect rect, Vector2 screen)
        {
            float w = Mathf.Abs(rect.width);
            float h = Mathf.Abs(rect.height);
            if (w <= 0f || h <= 0f) return false;
            return IntersectionArea(rect, screen) >= w * h * MinVisibleFraction;
        }

        /// <summary>
        /// НУЖНО ЛИ ЧИНИТЬ ПОЛОЖЕНИЕ ПАНЕЛИ. Истина — когда панель «показана», но оператор её не
        /// видит: команда отрапортовала успех, а на экране ничего не изменилось (это и есть R6-1).
        /// Отдельная функция, а не «!IsVisibleOnScreen», потому что решение о починке — это
        /// ПРАВИЛО, и оно обязано быть проверяемым отдельно от геометрии.
        /// </summary>
        public static bool NeedsPlacementRepair(bool shown, Rect rect, Vector2 screen)
        {
            return shown && !IsVisibleOnScreen(rect, screen);
        }

        // ============================================================================================
        //  ВТОРАЯ ПОЛОВИНА «ВИДНА»: ПАНЕЛЬ ОБЯЗАНА РИСОВАТЬСЯ (третий круг приёмки, 12.11.2026)
        //
        //  ЧТО БЫЛО. Первая версия правки R6-1 проверяла только флаг и прямоугольник. На планшете
        //  в AR этого НЕ ДОСТАТОЧНО: там десктопный оверлей штатно погашен сторожем
        //  (`KvXrDesktopOverlayGuard` раз в секунду выключает `Canvas.enabled` у канвасов
        //  десктопного интерфейса). Панель «включена», прямоугольник в экране — и ни один рендерер
        //  её не видит. Отсюда ровно то, что видел тестировщик: в журнале НИ ОДНОЙ строки «ПАНЕЛИ:»
        //  (починка не запускалась, ведь по флагу и геометрии всё «хорошо»), а на экране ничего.
        //
        //  ПОЭТОМУ «ВИДНА» = ФЛАГ + ГЕОМЕТРИЯ + РИСОВАНИЕ. Третье слагаемое — здесь, чистой
        //  функцией: три булевых значения, никакой сцены. Так его можно проверить тестом, который
        //  падал бы на старом коде (там третьего слагаемого не было вовсе).
        // ============================================================================================

        /// <summary>
        /// РИСУЕТСЯ ЛИ ПАНЕЛЬ ВООБЩЕ: она включена, её объект активен в иерархии и её канвас
        /// не выключен. Любое «нет» — панель существует только в памяти.
        /// </summary>
        public static bool IsRenderable(bool shown, bool activeInHierarchy, bool canvasEnabled)
        {
            return shown && activeInHierarchy && canvasEnabled;
        }

        /// <summary>
        /// НУЖНО ЛИ ВОЗВРАЩАТЬ РИСОВАНИЕ ПАНЕЛИ. Истина — когда оператор панель открыл, а её
        /// канвас/объект выключен: тогда команда обязана не «отрапортовать успех», а включить
        /// рисование и записать в журнал, что именно было включено.
        /// </summary>
        public static bool NeedsRenderRepair(bool shown, bool activeInHierarchy, bool canvasEnabled)
        {
            return shown && (!activeInHierarchy || !canvasEnabled);
        }
    }
}
