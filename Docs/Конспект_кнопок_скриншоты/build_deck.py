def add_table(slide, rows, left, top, width, height, col_w=None, fs=9):
    tbl_shape = slide.shapes.add_table(len(rows), len(rows[0]), Inches(left), Inches(top),
                                       Inches(width), Inches(height))
    tbl = tbl_shape.table
    if col_w:
        for i, w in enumerate(col_w):
            tbl.columns[i].width = Inches(w)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            cell = tbl.cell(ri, ci)
            cell.text = ""
            para = cell.text_frame.paragraphs[0]
            run = para.add_run(); run.text = str(val)
            run.font.size = Pt(fs if ri > 0 else fs + 0.5)
            run.font.bold = (ri == 0)
            run.font.color.rgb = DARK
    return tbl

def add_shot(slide, fname, left, top, height_in):
    path = os.path.join(SHOTS, fname)
    pic = slide.shapes.add_picture(path, Inches(left), Inches(top), height=Inches(height_in))
    return pic

def frame(slide, img_left, img_top, img_w_in, img_h_in, px_box, pw=1600, ph=2560, pad=6):
    """Красная рамка: px_box=(x1,y1,x2,y2) в пикселях PNG -> прямоугольник поверх картинки."""
    x1, y1, x2, y2 = px_box
    x1, y1, x2, y2 = x1 - pad, y1 - pad, x2 + pad, y2 + pad
    sx, sy = img_w_in / pw, img_h_in / ph
    left = img_left + x1 * sx
    top = img_top + y1 * sy
    w = (x2 - x1) * sx
    h = (y2 - y1) * sy
    sh = slide.shapes.add_shape(1, Inches(left), Inches(top), Inches(w), Inches(h))  # 1=rectangle
    sh.fill.background()
    sh.line.color.rgb = RED
    sh.line.width = Pt(2.5)
    return sh

